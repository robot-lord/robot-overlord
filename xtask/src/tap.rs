//! `cargo xtask update-tap VERSION SHA256SUMS [TAP_REPO]`: point the
//! Homebrew formula at a stable release. Writes Formula/rlord.rb in the tap
//! repo with the release's URLs and checksums, commits, pushes.
//!
//! Users: brew install robot-lord/tap/rlord   (brings tmux along)

use std::path::Path;

use anyhow::{bail, Context, Result};

use crate::cmd::{self, gh, git, TempDir};
use crate::version::{self, Target, Version, LINUX, MAC, REPO, TAP};

pub fn main(args: &[String], invoked_from: &Path) -> Result<()> {
    let (ver, sums, tap) = match args {
        [ver, sums] => (ver, sums, TAP),
        [ver, sums, tap] => (ver, sums, tap.as_str()),
        _ => return cmd::usage("usage: cargo xtask update-tap VERSION SHA256SUMS [TAP_REPO]"),
    };
    let ver = Version::parse(ver)?;
    if ver.is_dev() {
        bail!("update-tap: {ver} is a dev build; only stable releases go in the Homebrew tap");
    }
    // The path is the caller's, not relative to the repository root.
    update(&ver, &invoked_from.join(sums), tap)
}

pub fn update(ver: &Version, sums: &Path, tap: &str) -> Result<()> {
    let text =
        std::fs::read_to_string(sums).with_context(|| format!("reading {}", sums.display()))?;
    let formula = formula(ver, &text)
        .with_context(|| format!("update-tap: missing checksums in {}", sums.display()))?;

    let scratch = TempDir::new_in(&std::env::temp_dir(), "rlord-tap")?;
    let clone = scratch.path().join("tap");
    cmd::run(
        gh().args(["repo", "clone", tap])
            .arg(&clone)
            .args(["--", "-q"]),
    )?;
    std::fs::create_dir_all(clone.join("Formula"))?;
    std::fs::write(clone.join("Formula/rlord.rb"), formula)?;
    let in_clone = || {
        let mut c = git();
        c.current_dir(&clone);
        c
    };
    cmd::run(in_clone().args(["add", "Formula/rlord.rb"]))?;
    if cmd::succeeds(in_clone().args(["diff", "--cached", "--quiet"]))? {
        println!("update-tap: formula already at {ver}");
        return Ok(());
    }
    cmd::run(in_clone().args(["commit", "-qm", &format!("rlord {ver}")]))?;
    cmd::run(in_clone().args(["push", "-q"]))?;
    println!("update-tap: {tap} now installs rlord {ver}");
    Ok(())
}

/// The checksum SHA256SUMS lists for a file.
pub fn checksum<'a>(sums: &'a str, file: &str) -> Option<&'a str> {
    version::sha256sums(sums)
        .into_iter()
        .find_map(|(sum, name)| (name == file).then_some(sum))
}

/// Formula/rlord.rb for a release, from its SHA256SUMS.
fn formula(ver: &Version, sums: &str) -> Result<String> {
    let sha = |t: Target| match checksum(sums, &ver.tarball(t)) {
        Some(s) => Ok(s),
        None => bail!("no checksum for {}", ver.tarball(t)),
    };
    let (mac, lx, la) = (sha(MAC)?, sha(LINUX[0])?, sha(LINUX[1])?);
    let url = format!("https://github.com/{REPO}/releases/download/{}", ver.tag());
    Ok(format!(
        r##"# Generated by robot-overlord's `cargo xtask update-tap` on each stable release.
class Rlord < Formula
  desc "Manage your AI coding agents with AI, in tmux"
  homepage "https://github.com/{REPO}"
  version "{ver}"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "{url}/{mac_file}"
      sha256 "{mac}"
    end
  end

  on_linux do
    on_intel do
      url "{url}/{lx_file}"
      sha256 "{lx}"
    end
    on_arm do
      url "{url}/{la_file}"
      sha256 "{la}"
    end
  end

  depends_on "tmux"

  def install
    bin.install "rlord"
  end

  def caveats
    <<~EOS
      Once: rlord install-hooks   (lets rlord see what Claude Code and Codex are doing)
      Then: rlord
    EOS
  end

  test do
    assert_match "rlord #{{version}}", shell_output("#{{bin}}/rlord --version")
  end
end
"##,
        mac_file = ver.tarball(MAC),
        lx_file = ver.tarball(LINUX[0]),
        la_file = ver.tarball(LINUX[1]),
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    const SUMS: &str = "\
aaa  rlord-v1.0.0-aarch64-apple-darwin.tar.gz
bbb  rlord-v1.0.0-x86_64-unknown-linux-musl.tar.gz
ccc  rlord-v1.0.0-aarch64-unknown-linux-musl.tar.gz
ddd  rlord_1.0.0-1_amd64.deb
";

    #[test]
    fn finds_a_checksum_by_exact_name() {
        assert_eq!(checksum(SUMS, "rlord_1.0.0-1_amd64.deb"), Some("ddd"));
        assert_eq!(checksum(SUMS, "rlord_1.0.0-1_amd64"), None);
    }

    #[test]
    fn formula_has_each_platform() {
        let f = formula(&Version::parse("1.0.0").unwrap(), SUMS).unwrap();
        assert!(f.contains("  version \"1.0.0\"\n"));
        assert!(f.contains(
            "    on_arm do\n      url \"https://github.com/robot-lord/robot-overlord/releases/download/v1.0.0/rlord-v1.0.0-aarch64-apple-darwin.tar.gz\"\n      sha256 \"aaa\"\n"
        ));
        assert!(
            f.contains("rlord-v1.0.0-x86_64-unknown-linux-musl.tar.gz\"\n      sha256 \"bbb\"\n")
        );
        assert!(
            f.contains("rlord-v1.0.0-aarch64-unknown-linux-musl.tar.gz\"\n      sha256 \"ccc\"\n")
        );
        assert!(f.contains(
            "assert_match \"rlord #{version}\", shell_output(\"#{bin}/rlord --version\")"
        ));
    }

    #[test]
    fn formula_needs_every_checksum() {
        let partial = "aaa  rlord-v1.0.0-aarch64-apple-darwin.tar.gz\n";
        assert!(formula(&Version::parse("1.0.0").unwrap(), partial).is_err());
    }
}
