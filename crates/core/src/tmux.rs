    /// Real-tmux integration test of the actual module functions, on a
    /// private server socket. Gated: `RLORD_TMUX_TESTS=1 cargo test`.
    /// Serialized with a lock in case tests ever share the socket env.
    #[test]
    fn tmux_lifecycle_on_private_server() {
        if std::env::var("RLORD_TMUX_TESTS").as_deref() != Ok("1") {
            return;
        }
        // Safety: test process only; the daemon never sets this.
        std::env::set_var("RLORD_TMUX_SOCKET", "rlord-test");
        let _ = tmux_cmd().args(["kill-server"]).output();

        let name = "rlord_testsess";
        new_session(name, "/tmp", "sleep 30").unwrap();
        assert!(has_session(name));
        let (w, p) = window_pane_ids(name).unwrap();
        assert!(w.starts_with('@') && p.starts_with('%'));
        respawn_pane(name, "/tmp", "sleep 30").unwrap();

        // Key hints: a slim bar of rlord's own without a profile...
        let opt = |o: &str| run(&["show-options", "-v", "-t", &format!("={name}:"), o]).unwrap();
        set_hint_bar(name, "⌥d list · ⌥o overlord", false).unwrap();
        assert_eq!(opt("status").trim(), "on");
        assert_eq!(opt("status-right").trim(), HINTS_REF);
        assert!(opt(HINTS_OPT).contains("⌥d list"));
        // ...and in front of the profile's own status-right, once.
        run(&[
            "set-option",
            "-t",
            &format!("={name}:"),
            "status-right",
            "%H:%M",
        ])
        .unwrap();
        set_hint_bar(name, "⌥d list", true).unwrap();
        set_hint_bar(name, "⌥d list", true).unwrap();
        assert_eq!(opt("status-right").trim(), format!("{HINTS_REF}%H:%M"));
        if cfg!(target_os = "macos") {
            assert_eq!(key_label("M-d"), "⌥d");
        } else {
            assert_eq!(key_label("M-d"), "Alt-d");
            assert_eq!(key_label("C-M-x"), "Ctrl-Alt-x");
        }

        // Clickable hints: ranges count no width, and a status click on a
        // range runs that key's command (tmux's own click otherwise).
        assert_eq!(visible_len("#[range=user|rlord-list]⌥d list#[norange]"), 6);
        bind_nav_keys("/bin/rl'x", &[("M-d", "home"), ("M-o", "overlord")]).unwrap();
        for table in ["root", PROFILE_TABLE] {
            let k = run(&["list-keys", "-T", table, STATUS_CLICK]).unwrap();
            assert!(k.contains("mouse_status_range"), "{k}");
            assert!(
                k.contains("rlord-list") && k.contains("rlord-overlord"),
                "{k}"
            );
            assert!(k.contains("nav home") && k.contains("nav overlord"), "{k}");
            assert!(k.contains("switch-client -t ="), "{k}");
        }
        assert_eq!(
            status_click(&[]),
            ["switch-client", "-t", "="].map(String::from)
        );

        kill_session(name).unwrap();
        assert!(!has_session(name));

        let _ = tmux_cmd().args(["kill-server"]).output();
    }
