use crate::tmux_profile::TABLE as PROFILE_TABLE;

/// Marks a session whose profile is on.
const PROFILE_ON: &str = "@rlord_profile";

/// Session options rlord itself sets on agent sessions (kept when the
/// profile is turned off).
const RLORD_SESSION_OPTS: &[&str] = &[AGENT_PANE, PROFILE_ON];

/// The overlord keeps its own bar, but gets the user's keys: their key
/// table (root bindings, with rlord's nav keys), prefix, and copy-mode keys.
/// `on: false` takes them away again.
pub fn set_profile_keys(name: &str, on: bool) -> Result<()> {
    let t = format!("{}:", exact(name));
    if !on {
        for opt in ["key-table", "prefix", "prefix2"] {
            let _ = run(&["set-option", "-u", "-t", &t, opt]);
        }
        return Ok(());
    }
    let session = std::fs::read_to_string(crate::tmux_profile::session_path()).unwrap_or_default();
    let window = std::fs::read_to_string(crate::tmux_profile::window_path()).unwrap_or_default();
    for line in session.lines() {
        if let Some(rest) = line.strip_prefix("set-option ") {
            let (opt, val) = rest.split_once(' ').unwrap_or((rest, ""));
            if matches!(opt, "prefix" | "prefix2") {
                run(&["set-option", "-t", &t, opt, val.trim_matches('"')])?;
            }
        }
    }
    let mode_keys = window
        .lines()
        .find_map(|l| l.strip_prefix("set-option -w mode-keys "))
        .map(str::trim);
    if let Some(mk) = mode_keys {
        for w in run(&["list-windows", "-t", &exact(name), "-F", "#{window_id}"])?.lines() {
            run(&["set-option", "-w", "-t", w, "mode-keys", mk])?;
        }
    }
    run(&["set-option", "-t", &t, "key-table", PROFILE_TABLE])?;
    Ok(())
}

/// Key hints on an agent session's status bar: rlord's own keys (back to
/// the list, the overlord). With the user's profile on, they lead the
/// profile's status-right (re-applied after every re-import); without it,
/// the session gets a slim bar of its own: its name left, the hints right.
pub fn set_hint_bar(name: &str, hints: &str, profile_on: bool) -> Result<()> {
    let t = format!("{}:", exact(name));
    if hints.is_empty() {
        // No rlord keys bound: nothing to show (and no bar of our own).
        run(&["set-option", "-t", &t, HINTS_OPT, ""])?;
        if !profile_on {
            for opt in [
                "status",
                "status-style",
                "status-left",
                "status-left-length",
                "status-right",
                "status-right-length",
                "window-status-format",
                "window-status-current-format",
            ] {
                let _ = run(&["set-option", "-u", "-t", &t, opt]);
            }
        }
        return Ok(());
    }
    run(&[
        "set-option",
        "-t",
        &t,
        HINTS_OPT,
        &format!("#[fg=colour245] {hints} #[default]"),
    ])?;
    if profile_on {
        if run(&["show-options", "-v", "-t", &t, "status"])?.trim() == "off" {
            return Ok(()); // their profile hides the bar: respect it
        }
        let right = run(&["show-options", "-v", "-t", &t, "status-right"])?;
        let right = right.trim_end_matches('\n');
        if !right.contains(HINTS_REF) {
            run(&[
                "set-option",
                "-t",
                &t,
                "status-right",
                &format!("{HINTS_REF}{right}"),
            ])?;
            let len: usize = run(&["show-options", "-v", "-t", &t, "status-right-length"])?
                .trim()
                .parse()
                .unwrap_or(40);
            let want = (len + visible_len(hints) + 2).to_string();
            run(&["set-option", "-t", &t, "status-right-length", &want])?;
        }
        return Ok(());
    }
    for (opt, val) in [
        ("status", "on"),
        ("status-style", "bg=default,fg=colour245"),
        ("status-left", " #S "),
        ("status-left-length", "40"),
        ("status-right", HINTS_REF),
        ("status-right-length", "60"),
        ("window-status-format", ""),
        ("window-status-current-format", ""),
    ] {
        run(&["set-option", "-t", &t, opt, val])?;
    }
    Ok(())
}

/// Session option holding the styled key hints, and how status-right
/// refers to it (also how we tell it's already there).
const HINTS_OPT: &str = "@rlord-hints";
const HINTS_REF: &str = "#{E:@rlord-hints}";

/// Whether `key` in the root table runs rlord's nav (it's skipped when the
/// user's own binding already holds it).
pub fn nav_key_bound(key: &str) -> bool {
    run(&["list-keys", "-T", "root", key])
        .map(|o| o.contains("rlord") && o.contains(" nav "))
        .unwrap_or(false)
}

/// How a tmux key reads: `M-d` → `⌥d`, `C-x` → `⌃x` on a Mac; `Alt-d`,
/// `Ctrl-x` elsewhere.
pub fn key_label(key: &str) -> String {
    if cfg!(target_os = "macos") {
        key.replace("M-", "⌥").replace("C-", "⌃").replace("S-", "⇧")
    } else {
        key.replace("M-", "Alt-")
            .replace("C-", "Ctrl-")
            .replace("S-", "Shift-")
    }
}

/// Turn the user's imported tmux profile on or off for one session. Only
/// that session changes: its key table, its options, its windows. Requires
/// an imported profile to turn on.
pub fn set_profile(name: &str, on: bool) -> Result<()> {
    let t = format!("{}:", exact(name));
    let windows = || -> Result<Vec<String>> {
        Ok(
            run(&["list-windows", "-t", &exact(name), "-F", "#{window_id}"])?
                .lines()
                .map(str::to_string)
                .collect(),
        )
    };
    if on {
        let session = crate::tmux_profile::session_path();
        let window = crate::tmux_profile::window_path();
        if !crate::tmux_profile::exists() {
            bail!("no tmux profile imported — run `rlord tmux import`");
        }
        // Pin the agent pane before the user can split around it.
        if run(&["show-options", "-qv", "-t", &t, AGENT_PANE])?.is_empty() {
            pin_agent_pane(name)?;
        }
        let session = session.to_string_lossy();
        let window = window.to_string_lossy();
        run(&["source-file", "-t", &t, &session])?;
        for w in windows()? {
            run(&["source-file", "-t", &w, &window])?;
        }
        let hook = format!("source-file -q {}", shell_quote(&window));
        run(&["set-hook", "-t", &t, "after-new-window", &hook])?;
        run(&["set-option", "-t", &t, "key-table", PROFILE_TABLE])?;
        run(&["set-option", "-t", &t, PROFILE_ON, "1"])?;
        return Ok(());
    }
    if run(&["show-options", "-qv", "-t", &t, PROFILE_ON])?.is_empty() {
        return Ok(()); // never on: nothing of ours to undo
    }
    // Unset every session-local option except rlord's own, then every
    // window-local one except remain-on-exit (rlord's dead-pane handling).
    let mut args: Vec<String> = Vec::new();
    let mut unset = |target: &str, window: bool, listing: String, keep: &[&str]| {
        let mut names: Vec<&str> = listing
            .lines()
            .filter_map(|l| l.split([' ', '[']).next())
            .filter(|n| !n.is_empty() && !keep.contains(n))
            .collect();
        names.dedup();
        for n in names {
            if !args.is_empty() {
                args.push(";".into());
            }
            args.extend([
                "set-option".into(),
                if window { "-wu" } else { "-u" }.into(),
                "-t".into(),
                target.into(),
                n.into(),
            ]);
        }
    };
    unset(
        &t,
        false,
        run(&["show-options", "-t", &t])?,
        RLORD_SESSION_OPTS,
    );
    for w in windows()? {
        let listing = run(&["show-options", "-w", "-t", &w])?;
        unset(&w, true, listing, &["remain-on-exit"]);
    }
    if !args.is_empty() {
        let refs: Vec<&str> = args.iter().map(String::as_str).collect();
        run(&refs)?;
    }
    run(&["set-hook", "-u", "-t", &t, "after-new-window"])?;
    run(&["set-option", "-u", "-t", &t, PROFILE_ON])?;
    Ok(())
}

/// Whether a session's profile is on (per tmux, not the database).
pub fn profile_on(name: &str) -> bool {
    run(&[
        "show-options",
        "-qv",
        "-t",
        &format!("{}:", exact(name)),
        PROFILE_ON,
    ])
    .is_ok_and(|v| !v.is_empty())
}

// ---- navigation: server-wide root-table bindings + the "home" pointer ----

const HOME_OPTION: &str = "@rlord_home";

/// A requested navigation key that rlord refused to take over.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct KeyConflict {
    pub key: String,
    pub bound_to: String,
}

/// Install `key → run-shell "<bin> nav <verb>"` in the root key table for each
/// enabled binding, and remove rlord bindings left over from a previous
/// config. These keys are global to the tmux server, so a key that is the
/// user's prefix or already bound to something that isn't ours is **skipped**
/// and reported, never overridden. Idempotent.
pub fn bind_nav_keys(bin: &str, bindings: &[(&str, &str)]) -> Result<Vec<KeyConflict>> {
    for key in installed_nav_keys()? {
        if !bindings.iter().any(|(k, _)| *k == key) {
            let _ = run(&["unbind-key", "-n", &key]);
            let _ = run(&["unbind-key", "-T", PROFILE_TABLE, &key]);
        }
    }
    let prefix = run(&["show-options", "-gv", "prefix"]).unwrap_or_default();
    let root = root_bindings()?;
    let mut conflicts = Vec::new();
    let mut clickable = Vec::new();
    for (key, verb) in bindings {
        if *key == prefix {
            conflicts.push(KeyConflict {
                key: key.to_string(),
                bound_to: "your tmux prefix".into(),
            });
            continue;
        }
        if let Some(cmd) = root.get(*key).filter(|c| !c.contains("rlord nav ")) {
            conflicts.push(KeyConflict {
                key: key.to_string(),
                bound_to: cmd.clone(),
            });
            continue;
        }
        let cmd = format!("{} nav {verb}", shell_quote(bin));
        if let Some(range) = hint_range(verb) {
            clickable.push((range, cmd.clone()));
        }
        run(&["bind-key", "-n", key, "run-shell", "-b", &cmd])?;
        // Sessions with the user's profile use their own key table (it does
        // not fall back to root): rlord's keys must be there too.
        run(&[
            "bind-key",
            "-T",
            PROFILE_TABLE,
            key,
            "run-shell",
            "-b",
            &cmd,
        ])?;
    }
    // A click on a hint (`hint_range`) does what its key does. Only with
    // `[tmux] mouse` on; otherwise tmux's own status click.
    let mouse = crate::config::Config::load().map_or(true, |c| c.tmux.mouse);
    let click = if mouse { clickable } else { Vec::new() };
    for table in ["root", PROFILE_TABLE] {
        let mut args = vec!["bind-key", "-T", table, STATUS_CLICK];
        let cmd = status_click(&click);
        args.extend(cmd.iter().map(String::as_str));
        run(&args)?;
    }
    Ok(conflicts)
}

/// The status-line mouse key rlord binds for its clickable hints.
const STATUS_CLICK: &str = "MouseDown1Status";
/// tmux's own binding for it: switch to the clicked window.
const STATUS_CLICK_DEFAULT: &str = "switch-client -t =";

/// The status-line range a nav verb's hint carries, if it has a hint.
pub fn hint_range(verb: &str) -> Option<&'static str> {
    match verb {
        "home" => Some("rlord-list"),
        "overlord" => Some("rlord-overlord"),
        _ => None,
    }
}

/// `MouseDown1Status`'s command (as argv): the clicked hint's range runs
/// that key's command (`clicks`: range, command), anything else tmux's
/// default.
fn status_click(clicks: &[(&str, String)]) -> Vec<String> {
    let cond = |r: &str| format!("#{{==:#{{mouse_status_range}},{r}}}");
    let run_cmd = |c: &str| format!("run-shell -b {}", tmux_dq(c));
    let Some(((r0, c0), others)) = clicks.split_first() else {
        return STATUS_CLICK_DEFAULT.split(' ').map(String::from).collect();
    };
    // The others nest as the else, innermost (tmux's default) last.
    let mut rest = STATUS_CLICK_DEFAULT.to_string();
    for (r, c) in others.iter().rev() {
        rest = format!(
            "if-shell -F {} {} {}",
            tmux_dq(&cond(r)),
            tmux_dq(&run_cmd(c)),
            tmux_dq(&rest)
        );
    }
    // The outermost as argv: bind-key takes the command's words.
    vec!["if-shell".into(), "-F".into(), cond(r0), run_cmd(c0), rest]
}

/// How many characters a status-line string shows (`#[...]` styles and
/// ranges take none).
fn visible_len(s: &str) -> usize {
    let mut n = 0;
    let mut rest = s;
    while let Some(i) = rest.find("#[") {
        n += rest[..i].chars().count();
        rest = rest[i..].split_once(']').map_or("", |(_, r)| r);
    }
    n + rest.chars().count()
}

/// A tmux double-quoted string.
fn tmux_dq(s: &str) -> String {
    format!(
        "\"{}\"",
        s.replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('$', "\\$")
    )
}

/// `(key, command)` pairs of one key table.
pub type Bindings = Vec<(String, String)>;

/// What else is bound on rlord's server, for the key checks: the root
/// table, the user's imported table, and the user's prefixes (theirs from
/// the profile, and the server's if it has one).
pub fn key_env() -> (Bindings, Bindings, Vec<String>) {
    let table = |t: &str| {
        table_bindings(t)
            .map(|m| m.into_iter().collect())
            .unwrap_or_default()
    };
    let mut prefixes: Vec<String> = Vec::new();
    for opt in ["prefix", "prefix2"] {
        if let Ok(p) = run(&["show-options", "-gv", opt]) {
            prefixes.push(p);
        }
    }
    let session = std::fs::read_to_string(crate::tmux_profile::session_path()).unwrap_or_default();
    for line in session.lines() {
        if let Some(rest) = line.strip_prefix("set-option ") {
            let (opt, val) = rest.split_once(' ').unwrap_or((rest, ""));
            if matches!(opt, "prefix" | "prefix2") {
                prefixes.push(val.trim().trim_matches('"').to_string());
            }
        }
    }
    prefixes.retain(|p| !p.is_empty() && p != "None");
    prefixes.dedup();
    (table("root"), table(PROFILE_TABLE), prefixes)
}

/// Point a session at another key table (`None`: back to its default).
/// The key screen points the list at an empty one while it listens, so the
/// key it tests reaches it even if rlord already binds it.
pub fn set_key_table(session: &str, table: Option<&str>) -> Result<()> {
    let t = format!("{}:", exact(session));
    match table {
        Some(tb) => run(&["set-option", "-t", &t, "key-table", tb])?,
        None => run(&["set-option", "-u", "-t", &t, "key-table"])?,
    };
    Ok(())
}

/// The terminal the user's client runs in (`iTerm2 3.5.0`; may be empty).
pub fn client_termtype() -> String {
    run(&["display-message", "-p", "#{client_termtype}"]).unwrap_or_default()
}

/// `key → command` for every root-table binding on the server.
fn root_bindings() -> Result<std::collections::HashMap<String, String>> {
    table_bindings("root")
}

/// `key → command` for every binding in one key table.
fn table_bindings(table: &str) -> Result<std::collections::HashMap<String, String>> {
    let out = match run(&["list-keys", "-T", table]) {
        Ok(o) => o,
        Err(_) => return Ok(Default::default()), // no server
    };
    Ok(out
        .lines()
        .filter_map(|l| {
            // bind-key [-r] -T root <key> <command...>
            let mut parts = l
                .split_whitespace()
                .skip(1)
                .skip_while(|p| p.starts_with('-'));
            let (Some(_root), Some(key)) = (parts.next(), parts.next()) else {
                return None;
            };
            Some((key.to_string(), parts.collect::<Vec<_>>().join(" ")))
        })
        .collect())
}

/// Remove every rlord navigation binding, whatever key it is on.
pub fn unbind_nav_keys(bindings: &[(&str, &str)]) -> Result<()> {
    let mut keys = installed_nav_keys()?;
    keys.extend(bindings.iter().map(|(k, _)| k.to_string()));
    for key in keys {
        // Unbinding a key that isn't bound is not an error worth surfacing.
        let _ = run(&["unbind-key", "-n", &key]);
        let _ = run(&["unbind-key", "-T", PROFILE_TABLE, &key]);
    }
    Ok(())
}

/// Root-table keys currently bound to `rlord nav ...` on this server.
fn installed_nav_keys() -> Result<Vec<String>> {
    let out = match run(&["list-keys", "-T", "root"]) {
        Ok(o) => o,
        Err(_) => return Ok(vec![]), // no server: nothing installed
    };
    Ok(out
        .lines()
        .filter(|l| l.contains("rlord nav "))
        .filter_map(|l| l.split_whitespace().nth(3).map(str::to_string))
        .collect())
}

/// Record where the TUI lives so `nav home` can find it. Empty = "no home;
/// detach instead" (the TUI sets this when it attaches from outside tmux).
pub fn set_home(session: &str) -> Result<()> {
    run(&["set-option", "-g", HOME_OPTION, session])?;
    Ok(())
}

pub fn home() -> Option<String> {
    run(&["show-options", "-gqv", HOME_OPTION])
        .ok()
        .filter(|s| !s.is_empty())
}

/// Session of the pane this process runs in (valid inside tmux / run-shell).
pub fn current_session() -> Option<String> {
    if !inside_rlord() {
        return None;
    }
    // This process's own pane ($TMUX_PANE), not whatever the active client
    // shows: a TUI restarted by `rlord reset` while the terminal is on an
    // agent session must still record its own session as home.
    let pane = std::env::var("TMUX_PANE").ok().filter(|p| !p.is_empty());
    let own = pane.as_deref().and_then(|p| {
        run(&["display-message", "-p", "-t", p, "#{session_name}"])
            .ok()
            .filter(|s| !s.is_empty())
    });
    // No pane, or a stale one (a key binding's job can inherit an id that
    // isn't on this server): the current client's session, as before.
    own.or_else(|| {
        run(&["display-message", "-p", "#{session_name}"])
            .ok()
            .filter(|s| !s.is_empty())
    })
}

/// Flash a message on the current client's status line.
pub fn display_message(msg: &str) -> Result<()> {
    run(&["display-message", msg])?;
    Ok(())
}

pub fn switch_client(session: &str) -> Result<()> {
    run(&["switch-client", "-t", &exact(session)])?;
    Ok(())
}

pub fn detach_client() -> Result<()> {
    run(&["detach-client"])?;
    Ok(())
}

