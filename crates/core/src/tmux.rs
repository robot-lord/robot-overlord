/// Paste text into a pane as a bracketed paste (so multi-line text arrives as
/// one paste, not as a sequence of Enter-terminated lines).
pub fn paste(pane: &str, text: &str) -> Result<()> {
    use std::io::Write;
    let mut child = tmux_cmd()
        .args(["load-buffer", "-b", "rlord_paste", "-"])
        .stdin(std::process::Stdio::piped())
        .spawn()
        .context("running tmux")?;
    child
        .stdin
        .take()
        .context("no stdin")?
        .write_all(text.as_bytes())?;
    if !child.wait()?.success() {
        bail!("tmux load-buffer failed");
    }
    run(&["paste-buffer", "-p", "-d", "-b", "rlord_paste", "-t", pane])?;
    Ok(())
}

