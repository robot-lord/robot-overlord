    fn user_client_is_most_recent() {
        let c = |n: &str, a| Client {
            name: n.into(),
            session: "s".into(),
            activity: a,
        };
        let clients = vec![c("/dev/ttys1", 10), c("/dev/ttys2", 20)];
        assert_eq!(user_client(&clients, None).unwrap().name, "/dev/ttys2");
        assert!(user_client(&[], None).is_none());
        // A terminal showing rlord beats a more recently active one that isn't.
        let mut clients = clients;
        clients[0].session = "rlord_01abc".into();
        assert_eq!(user_client(&clients, None).unwrap().name, "/dev/ttys1");
        clients[0].session = "home".into();
        assert_eq!(
            user_client(&clients, Some("home")).unwrap().name,
            "/dev/ttys1"
        );
    }

