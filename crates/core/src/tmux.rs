//! tmux supervision. rlord runs its **own tmux server** (`tmux -L rlord`)
//! with a generated config (no status bar, no prefix, only rlord's keys): the
//! user's personal tmux is never touched, and tmux is an implementation
//! detail they don't see. One tmux session per rlord session; its agent runs
//! in one pane, pinned by id (`@rlord_pane`) — with the user's tmux profile
//! on (tmux_profile.rs) the user may add splits and windows around it. Session names are Docker-style `rlord-<adjective>-<noun>`
//! (names.rs), minted once and stored; never derived from the display name. `remain-on-exit` is set so an exited agent leaves a dead
//! pane (restartable in place via `respawn-pane -k`) instead of tearing the
//! tmux session down.
//!
//! Targeting rule: windows and panes are addressed by their unique tmux ids
//! (`@n`/`%n`, resolved via `list-panes`), NEVER by index — the user's tmux
//! config may set base-index/pane-base-index and shift all numbering (this
//! bit us on first contact with a real config).

use std::process::Command;

use anyhow::{bail, Context, Result};

/// tmux target for exact session-name match (`=` disables prefix matching).
fn exact(name: &str) -> String {
    format!("={name}")
}

/// Socket name of rlord's private tmux server (`tmux -L <name>`). Tests
/// override it with `RLORD_TMUX_SOCKET`.
pub fn socket_name() -> String {
    std::env::var("RLORD_TMUX_SOCKET")
        .ok()
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "rlord".to_string())
}

/// Config the private server starts with (written next to the database).
pub fn conf_path() -> std::path::PathBuf {
    crate::paths::data_dir().join("tmux.conf")
}

const CONF: &str = r#"# Generated by rlord — the config of rlord's private tmux server.
# Regenerated on every start; put your own tweaks in tmux.local.conf beside it.
set -g status off
set -g prefix None
set -g prefix2 None
unbind-key -a -T prefix
set -g mouse on
set -g escape-time 10
set -g history-limit 50000
set -g focus-events on
set -g extended-keys on
set -g default-terminal "tmux-256color"
set -as terminal-features ",*:RGB"
set -as terminal-features ",xterm*:extkeys"
set -g set-titles on
set -g set-titles-string '#S'
set -g detach-on-destroy on
"#;

/// Write the server config (cheap; idempotent).
pub fn write_conf() -> Result<()> {
    let p = conf_path();
    if let Some(d) = p.parent() {
        std::fs::create_dir_all(d)?;
    }
    let local = p.with_file_name("tmux.local.conf");
    let mut conf = CONF.to_string();
    // The user's imported tmux profile: its bindings live in tables only
    // sessions with the profile on can reach (see tmux_profile.rs).
    let profile = crate::tmux_profile::keys_path();
    if profile.exists() {
        conf.push_str(&format!(
            "source-file -q {}\n",
            shell_quote(&profile.to_string_lossy())
        ));
    }
    if local.exists() {
        conf.push_str(&format!(
            "source-file {}\n",
            shell_quote(&local.to_string_lossy())
        ));
    }
    if std::fs::read_to_string(&p).ok().as_deref() != Some(conf.as_str()) {
        std::fs::write(&p, conf)?;
    }
    Ok(())
}

/// Kill rlord's whole tmux server (every session in it).
pub fn kill_server() -> Result<()> {
    let _ = run(&["kill-server"]); // "no server running" is fine
    Ok(())
}

/// Re-apply the generated config to a running server.
pub fn source_conf() -> Result<()> {
    write_conf()?;
    let p = conf_path();
    run(&["source-file", &p.to_string_lossy()])?;
    Ok(())
}

/// Restart the program in a session's pane (`respawn-pane -k`).
pub fn respawn_plain(session: &str, cmd: &str) -> Result<()> {
    let (_, pane) = window_pane_ids(session)?;
    run(&["respawn-pane", "-k", "-t", &pane, cmd])?;
    Ok(())
}

/// Whether a session on the user's default server is one an older rlord
/// made: `rlord_overlord`, `rlord_<session id>` (26-char lowercase ULID), or
/// the home session `rlord` while it is actually running rlord. A personal
/// session that merely has a similar name is left alone.
fn is_legacy_rlord_session(name: &str, pane_commands: impl FnOnce() -> String) -> bool {
    if name == "rlord" {
        return pane_commands().lines().any(|c| c.trim() == "rlord");
    }
    match name.strip_prefix("rlord_") {
        Some("overlord") => true,
        Some(id) => {
            id.len() == 26
                && id
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit())
        }
        None => false,
    }
}

/// Remove what older rlord versions left on the user's **default** tmux
/// server: the sessions it made (see `is_legacy_rlord_session`) and rlord's
/// root-table key bindings. Returns the session names killed.
pub fn cleanup_default_server() -> Vec<String> {
    // Only the real install has legacy state there; a test/alternate
    // server must never reach into the user's default tmux.
    if socket_name() != "rlord" {
        return vec![];
    }
    let tmux = |args: &[&str]| {
        Command::new("tmux")
            .env_remove("TMUX")
            .args(args)
            .output()
            .ok()
            .filter(|o| o.status.success())
            .map(|o| String::from_utf8_lossy(&o.stdout).to_string())
    };
    let mut killed = Vec::new();
    for name in tmux(&["list-sessions", "-F", "#{session_name}"])
        .unwrap_or_default()
        .lines()
    {
        let panes = || {
            tmux(&[
                "list-panes",
                "-s",
                "-t",
                &exact(name),
                "-F",
                "#{pane_current_command}",
            ])
            .unwrap_or_default()
        };
        if is_legacy_rlord_session(name, panes)
            && tmux(&["kill-session", "-t", &exact(name)]).is_some()
        {
            killed.push(name.to_string());
        }
    }
    for line in tmux(&["list-keys", "-T", "root"])
        .unwrap_or_default()
        .lines()
    {
        if line.contains("rlord nav ") {
            if let Some(key) = line.split_whitespace().nth(3) {
                tmux(&["unbind-key", "-n", key]);
            }
        }
    }
    killed
}

/// A `tmux` command aimed at rlord's server (used for exec'ing attach).
pub fn command() -> Command {
    tmux_cmd()
}

/// Whether this process runs inside rlord's tmux server (as opposed to
/// outside tmux, or inside the user's own tmux).
pub fn inside_rlord() -> bool {
    let Some(t) = std::env::var_os("TMUX") else {
        return false;
    };
    let t = t.to_string_lossy();
    let sock = t.split(',').next().unwrap_or("");
    std::path::Path::new(sock)
        .file_name()
        .is_some_and(|n| n.to_string_lossy() == socket_name())
}

fn tmux_cmd() -> Command {
    static CONF_WRITTEN: std::sync::Once = std::sync::Once::new();
    CONF_WRITTEN.call_once(|| {
        if let Err(e) = write_conf() {
            tracing::warn!(error = %e, "writing rlord tmux.conf");
        }
    });
    let mut c = Command::new("tmux");
    // Inside rlord's server, TMUX tells tmux which client/pane "current"
    // means; anywhere else it would point at the user's own tmux.
    if !inside_rlord() {
        c.env_remove("TMUX");
    }
    c.args(["-L", &socket_name(), "-f"]);
    c.arg(conf_path());
    // Without a UTF-8 locale (e.g. the daemon under launchd, which starts
    // with no LANG) tmux rewrites tabs and non-ASCII in its output to `_`:
    // parsing breaks and captured screens are mangled.
    let utf8 = ["LC_ALL", "LC_CTYPE", "LANG"]
        .iter()
        .find_map(|k| std::env::var(k).ok().filter(|v| !v.is_empty()))
        .is_some_and(|v| v.to_ascii_uppercase().replace('-', "").contains("UTF8"));
    if !utf8 {
        c.env("LC_CTYPE", "en_US.UTF-8");
    }
    c
}

fn run(args: &[&str]) -> Result<String> {
    let out = tmux_cmd()
        .args(args)
        .output()
        .context("running tmux (is tmux installed?)")?;
    if !out.status.success() {
        bail!(
            "tmux {} failed: {}",
            args.first().unwrap_or(&"?"),
            String::from_utf8_lossy(&out.stderr).trim()
        );
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

/// Rename a tmux session in place (attached clients stay attached).
pub fn rename_session(old: &str, new: &str) -> Result<()> {
    run(&["rename-session", "-t", &exact(old), new])?;
    Ok(())
}

pub fn has_session(name: &str) -> bool {
    tmux_cmd()
        .args(["has-session", "-t", &exact(name)])
        .output()
        .map(|o| o.status.success())
        .unwrap_or(false)
}

/// Session option naming the agent's pane. With the user's tmux profile a
/// session can have splits and windows, and the agent's pane isn't
/// necessarily listed first (`split-window -b` puts the new one ahead).
const AGENT_PANE: &str = "@rlord_pane";

/// Resolve the session's agent window and pane to their unique tmux ids:
/// the pinned pane if it is still there, else the first one.
/// Name the agent's window after the session (`label`) and stop tmux from
/// renaming it after the running program; Claude Code's process shows up
/// as its version number (`2.1.322`).
pub fn name_agent_window(name: &str, label: &str) -> Result<()> {
    let (window_id, _) = window_pane_ids(name)?;
    run(&["rename-window", "-t", &window_id, label])?;
    run(&[
        "set-option",
        "-w",
        "-t",
        &window_id,
        "automatic-rename",
        "off",
    ])?;
    Ok(())
}

fn window_pane_ids(name: &str) -> Result<(String, String)> {
    let out = run(&[
        "list-panes",
        "-s",
        "-t",
        &exact(name),
        "-F",
        &format!("#{{window_id}} #{{pane_id}} #{{{AGENT_PANE}}}"),
    ])?;
    let panes: Vec<(&str, &str, &str)> = out
        .lines()
        .filter_map(|l| {
            let mut f = l.splitn(3, ' ');
            Some((f.next()?, f.next()?, f.next().unwrap_or("")))
        })
        .collect();
    let (w, p, _) = panes
        .iter()
        .find(|(_, p, pinned)| p == pinned)
        .or_else(|| panes.first())
        .context("session has no panes")?;
    Ok((w.to_string(), p.to_string()))
}

/// Record the session's current agent pane (first pane, if none recorded).
fn pin_agent_pane(name: &str) -> Result<()> {
    let (_, pane) = window_pane_ids(name)?;
    run(&[
        "set-option",
        "-t",
        &format!("{}:", exact(name)),
        AGENT_PANE,
        &pane,
    ])?;
    Ok(())
}

/// POSIX single-quote escaping.
pub fn shell_quote(s: &str) -> String {
    if !s.is_empty()
        && s.chars()
            .all(|c| c.is_ascii_alphanumeric() || "-_./=:@%+,".contains(c))
    {
        s.to_string()
    } else {
        format!("'{}'", s.replace('\'', r"'\''"))
    }
}

/// Build the pane command: `exec env K=V... argv...`, fully quoted. Env is
/// embedded in the command (rather than tmux session env) so respawns are
/// deterministic and the vars reach hook subprocesses.
pub fn pane_command(env: &[(String, String)], argv: &[String]) -> String {
    let mut parts = vec!["exec".to_string(), "env".to_string()];
    for (k, v) in env {
        parts.push(shell_quote(&format!("{k}={v}")));
    }
    parts.extend(argv.iter().map(|a| shell_quote(a)));
    parts.join(" ")
}

pub fn new_session(name: &str, cwd: &str, pane_cmd: &str) -> Result<()> {
    run(&["new-session", "-d", "-s", name, "-c", cwd, pane_cmd])?;
    // Dead pane instead of dead session when the agent exits. If this
    // follow-up fails, tear the half-made session down rather than leaking it.
    let configure = || -> Result<()> {
        let (window_id, _) = window_pane_ids(name)?;
        run(&["set-option", "-w", "-t", &window_id, "remain-on-exit", "on"])?;
        pin_agent_pane(name)?;
        Ok(())
    };
    if let Err(e) = configure() {
        let _ = kill_session(name);
        return Err(e);
    }
    Ok(())
}

/// A detached session with no rlord pane conventions (used for the TUI's
/// home session).
pub fn new_plain_session(name: &str, cwd: &str, cmd: &str) -> Result<()> {
    run(&["new-session", "-d", "-s", name, "-c", cwd, cmd])?;
    Ok(())
}

pub fn respawn_pane(name: &str, cwd: &str, pane_cmd: &str) -> Result<()> {
    let (_, pane_id) = window_pane_ids(name)?;
    run(&["respawn-pane", "-k", "-c", cwd, "-t", &pane_id, pane_cmd])?;
    Ok(())
}

/// Visible contents of the session's pane (for previews), plain text.
pub fn capture_pane(name: &str) -> Result<String> {
    let (_, pane_id) = window_pane_ids(name)?;
    run(&["capture-pane", "-p", "-t", &pane_id])
}

/// Same, with ANSI colour/attribute escapes preserved (`-e`).
pub fn capture_pane_ansi(name: &str) -> Result<String> {
    let (_, pane_id) = window_pane_ids(name)?;
    run(&["capture-pane", "-p", "-e", "-t", &pane_id])
}

pub fn kill_session(name: &str) -> Result<()> {
    if has_session(name) {
        run(&["kill-session", "-t", &exact(name)])?;
    }
    Ok(())
}

// ---- clients (the overlord moves the user's terminal around) ----

/// A terminal attached to the tmux server.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Client {
    pub name: String,
    pub session: String,
    /// Last input/output activity, epoch seconds.
    pub activity: i64,
}

pub fn list_clients() -> Vec<Client> {
    let Ok(out) = run(&[
        "list-clients",
        "-F",
        // Space-separated: none of the leading fields contain spaces; the
        // session name (which may) comes last.
        "#{client_activity} #{client_control_mode} #{client_name} #{session_name}",
    ]) else {
        return vec![]; // no server
    };
    out.lines()
        .filter_map(|l| {
            let mut f = l.splitn(4, ' ');
            let activity = f.next()?.parse().ok()?;
            if f.next()? == "1" {
                return None; // control-mode client (a program, not a person)
            }
            Some(Client {
                activity,
                name: f.next()?.to_string(),
                session: f.next()?.to_string(),
            })
        })
        .collect()
}

/// The user's terminal: the most recently active client that is showing
/// rlord (its home session or an rlord session), else the most recently
/// active client at all.
pub fn user_client<'a>(clients: &'a [Client], home: Option<&str>) -> Option<&'a Client> {
    let ours = |c: &&Client| Some(c.session.as_str()) == home || c.session.starts_with("rlord");
    clients
        .iter()
        .filter(ours)
        .max_by_key(|c| c.activity)
        .or_else(|| clients.iter().max_by_key(|c| c.activity))
}

/// Point a specific client at a session.
pub fn switch_client_of(client: &str, session: &str) -> Result<()> {
    run(&["switch-client", "-c", client, "-t", &exact(session)])?;
    Ok(())
}

/// Mark a session visually: its own status-bar style and left label
/// (session-scoped options; other sessions keep the user's status bar).
pub fn style_session(session: &str, status_style: &str, status_left: &str) -> Result<()> {
    // `set-option -t =name` doesn't resolve on tmux 3.8; `=name:` does.
    let t = format!("{}:", exact(session));
    run(&["set-option", "-t", &t, "status", "on"])?;
    run(&["set-option", "-t", &t, "status-style", status_style])?;
    // Just the label: no window list, no clock/host on the right.
    run(&["set-option", "-t", &t, "status-right", ""])?;
    run(&["set-option", "-t", &t, "window-status-format", ""])?;
    run(&["set-option", "-t", &t, "window-status-current-format", ""])?;
    run(&["set-option", "-t", &t, "status-left", status_left])?;
    run(&["set-option", "-t", &t, "status-left-length", "40"])?;
    Ok(())
}

/// Name of the client this process runs under (valid inside tmux / run-shell).
pub fn current_client() -> Option<String> {
    if !inside_rlord() {
        return None;
    }
    run(&["display-message", "-p", "#{client_name}"])
        .ok()
        .filter(|s| !s.is_empty())
}

/// Open a popup on `client` running `cmd`, without waiting for it to close
/// (`display-popup` blocks until then). Closes any popup already open there.
pub fn open_popup(client: &str, width: &str, height: &str, title: &str, cmd: &str) -> Result<()> {
    let _ = close_popup(client);
    let mut child = tmux_cmd()
        .args([
            "display-popup",
            "-c",
            client,
            "-E",
            "-w",
            width,
            "-h",
            height,
            "-b",
            "rounded",
            "-S",
            "fg=colour141",
            "-T",
            title,
            cmd,
        ])
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .spawn()
        .context("running tmux")?;
    // Reap it whenever the popup closes.
    std::thread::spawn(move || {
        let _ = child.wait();
    });
    Ok(())
}

/// Close the popup on `client`, if any.
pub fn close_popup(client: &str) -> Result<()> {
    run(&["display-popup", "-C", "-c", client])?;
    Ok(())
}

// ---- embedding: another program draws a session's pane and types into it ----

/// The session's pane id (`%n`).
pub fn pane_id(session: &str) -> Result<String> {
    Ok(window_pane_ids(session)?.1)
}

/// Size the session's window to exactly `cols`×`rows` (the embedding view),
/// so the agent lays itself out for the space it is shown in.
pub fn resize_window(session: &str, cols: u16, rows: u16) -> Result<()> {
    let (window_id, _) = window_pane_ids(session)?;
    run(&[
        "resize-window",
        "-t",
        &window_id,
        "-x",
        &cols.to_string(),
        "-y",
        &rows.to_string(),
    ])?;
    Ok(())
}

/// Hand the window's size back to tmux. `resize-window` pins a window to
/// `window-size manual`; unsetting that lets it follow whichever terminal
/// views it (the server default, `latest`).
pub fn auto_size_window(session: &str) -> Result<()> {
    let (window_id, _) = window_pane_ids(session)?;
    // (`resize-window -A` would pin it to manual again — just unset.)
    run(&["set-option", "-w", "-u", "-t", &window_id, "window-size"])?;
    Ok(())
}

/// One frame of a pane: its visible rows with ANSI attributes (trailing
/// blank rows kept, so row indices match the cursor), plus the cursor.
pub struct PaneFrame {
    pub ansi: String,
    pub cursor_x: u16,
    pub cursor_y: u16,
    pub cursor_visible: bool,
}

pub fn capture_frame(pane: &str) -> Result<PaneFrame> {
    // One tmux invocation for both: the cursor line, then the screen.
    let out = tmux_cmd()
        .args([
            "display-message",
            "-p",
            "-t",
            pane,
            "#{cursor_x} #{cursor_y} #{cursor_flag}",
            ";",
            "capture-pane",
            "-p",
            "-e",
            "-t",
            pane,
        ])
        .output()
        .context("running tmux")?;
    if !out.status.success() {
        bail!(
            "tmux capture failed: {}",
            String::from_utf8_lossy(&out.stderr).trim()
        );
    }
    let text = String::from_utf8_lossy(&out.stdout);
    let (head, ansi) = text.split_once('\n').unwrap_or((&text, ""));
    let mut f = head
        .split_whitespace()
        .map(|v| v.parse::<u16>().unwrap_or(0));
    Ok(PaneFrame {
        cursor_x: f.next().unwrap_or(0),
        cursor_y: f.next().unwrap_or(0),
        cursor_visible: f.next().unwrap_or(0) == 1,
        ansi: ansi.to_string(),
    })
}

/// Send tmux key names (`Enter`, `C-c`, `M-x`, `Up`, …) to a pane.
pub fn send_keys(pane: &str, keys: &[&str]) -> Result<()> {
    let mut args = vec!["send-keys", "-t", pane];
    args.extend_from_slice(keys);
    run(&args)?;
    Ok(())
}

/// Type literal text into a pane.
pub fn send_text(pane: &str, text: &str) -> Result<()> {
    run(&["send-keys", "-t", pane, "-l", "--", text])?;
    Ok(())
}

/// Paste text into a pane as a bracketed paste (so multi-line text arrives as
/// one paste, not as a sequence of Enter-terminated lines).
pub fn paste(pane: &str, text: &str) -> Result<()> {
    use std::io::Write;
    let mut child = tmux_cmd()
        .args(["load-buffer", "-b", "rlord_paste", "-"])
        .stdin(std::process::Stdio::piped())
        .spawn()
        .context("running tmux")?;
    child
        .stdin
        .take()
        .context("no stdin")?
        .write_all(text.as_bytes())?;
    if !child.wait()?.success() {
        bail!("tmux load-buffer failed");
    }
    run(&["paste-buffer", "-p", "-d", "-b", "rlord_paste", "-t", pane])?;
    Ok(())
}

// ---- the user's tmux profile, per session ----

use crate::tmux_profile::TABLE as PROFILE_TABLE;

/// Marks a session whose profile is on.
const PROFILE_ON: &str = "@rlord_profile";

/// Session options rlord itself sets on agent sessions (kept when the
/// profile is turned off).
const RLORD_SESSION_OPTS: &[&str] = &[AGENT_PANE, PROFILE_ON];

/// Turn the user's imported tmux profile on or off for one session. Only
/// that session changes: its key table, its options, its windows. Requires
/// an imported profile to turn on.
pub fn set_profile(name: &str, on: bool) -> Result<()> {
    let t = format!("{}:", exact(name));
    let windows = || -> Result<Vec<String>> {
        Ok(
            run(&["list-windows", "-t", &exact(name), "-F", "#{window_id}"])?
                .lines()
                .map(str::to_string)
                .collect(),
        )
    };
    if on {
        let session = crate::tmux_profile::session_path();
        let window = crate::tmux_profile::window_path();
        if !crate::tmux_profile::exists() {
            bail!("no tmux profile imported — run `rlord tmux import`");
        }
        // Pin the agent pane before the user can split around it.
        if run(&["show-options", "-qv", "-t", &t, AGENT_PANE])?.is_empty() {
            pin_agent_pane(name)?;
        }
        let session = session.to_string_lossy();
        let window = window.to_string_lossy();
        run(&["source-file", "-t", &t, &session])?;
        for w in windows()? {
            run(&["source-file", "-t", &w, &window])?;
        }
        let hook = format!("source-file -q {}", shell_quote(&window));
        run(&["set-hook", "-t", &t, "after-new-window", &hook])?;
        run(&["set-option", "-t", &t, "key-table", PROFILE_TABLE])?;
        run(&["set-option", "-t", &t, PROFILE_ON, "1"])?;
        return Ok(());
    }
    if run(&["show-options", "-qv", "-t", &t, PROFILE_ON])?.is_empty() {
        return Ok(()); // never on: nothing of ours to undo
    }
    // Unset every session-local option except rlord's own, then every
    // window-local one except remain-on-exit (rlord's dead-pane handling).
    let mut args: Vec<String> = Vec::new();
    let mut unset = |target: &str, window: bool, listing: String, keep: &[&str]| {
        let mut names: Vec<&str> = listing
            .lines()
            .filter_map(|l| l.split([' ', '[']).next())
            .filter(|n| !n.is_empty() && !keep.contains(n))
            .collect();
        names.dedup();
        for n in names {
            if !args.is_empty() {
                args.push(";".into());
            }
            args.extend([
                "set-option".into(),
                if window { "-wu" } else { "-u" }.into(),
                "-t".into(),
                target.into(),
                n.into(),
            ]);
        }
    };
    unset(
        &t,
        false,
        run(&["show-options", "-t", &t])?,
        RLORD_SESSION_OPTS,
    );
    for w in windows()? {
        let listing = run(&["show-options", "-w", "-t", &w])?;
        unset(&w, true, listing, &["remain-on-exit"]);
    }
    if !args.is_empty() {
        let refs: Vec<&str> = args.iter().map(String::as_str).collect();
        run(&refs)?;
    }
    run(&["set-hook", "-u", "-t", &t, "after-new-window"])?;
    run(&["set-option", "-u", "-t", &t, PROFILE_ON])?;
    Ok(())
}

/// Whether a session's profile is on (per tmux, not the database).
pub fn profile_on(name: &str) -> bool {
    run(&[
        "show-options",
        "-qv",
        "-t",
        &format!("{}:", exact(name)),
        PROFILE_ON,
    ])
    .is_ok_and(|v| !v.is_empty())
}

// ---- navigation: server-wide root-table bindings + the "home" pointer ----

const HOME_OPTION: &str = "@rlord_home";

/// A requested navigation key that rlord refused to take over.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct KeyConflict {
    pub key: String,
    pub bound_to: String,
}

/// Install `key → run-shell "<bin> nav <verb>"` in the root key table for each
/// enabled binding, and remove rlord bindings left over from a previous
/// config. These keys are global to the tmux server, so a key that is the
/// user's prefix or already bound to something that isn't ours is **skipped**
/// and reported, never overridden. Idempotent.
pub fn bind_nav_keys(bin: &str, bindings: &[(&str, &str)]) -> Result<Vec<KeyConflict>> {
    for key in installed_nav_keys()? {
        if !bindings.iter().any(|(k, _)| *k == key) {
            let _ = run(&["unbind-key", "-n", &key]);
            let _ = run(&["unbind-key", "-T", PROFILE_TABLE, &key]);
        }
    }
    let prefix = run(&["show-options", "-gv", "prefix"]).unwrap_or_default();
    let root = root_bindings()?;
    let mut conflicts = Vec::new();
    for (key, verb) in bindings {
        if *key == prefix {
            conflicts.push(KeyConflict {
                key: key.to_string(),
                bound_to: "your tmux prefix".into(),
            });
            continue;
        }
        if let Some(cmd) = root.get(*key).filter(|c| !c.contains("rlord nav ")) {
            conflicts.push(KeyConflict {
                key: key.to_string(),
                bound_to: cmd.clone(),
            });
            continue;
        }
        let cmd = format!("{} nav {verb}", shell_quote(bin));
        run(&["bind-key", "-n", key, "run-shell", "-b", &cmd])?;
        // Sessions with the user's profile use their own key table (it does
        // not fall back to root): rlord's keys must be there too.
        run(&[
            "bind-key",
            "-T",
            PROFILE_TABLE,
            key,
            "run-shell",
            "-b",
            &cmd,
        ])?;
    }
    Ok(conflicts)
}

/// `key → command` for every root-table binding on the server.
fn root_bindings() -> Result<std::collections::HashMap<String, String>> {
    let out = match run(&["list-keys", "-T", "root"]) {
        Ok(o) => o,
        Err(_) => return Ok(Default::default()), // no server
    };
    Ok(out
        .lines()
        .filter_map(|l| {
            // bind-key [-r] -T root <key> <command...>
            let mut parts = l
                .split_whitespace()
                .skip(1)
                .skip_while(|p| p.starts_with('-'));
            let (Some(_root), Some(key)) = (parts.next(), parts.next()) else {
                return None;
            };
            Some((key.to_string(), parts.collect::<Vec<_>>().join(" ")))
        })
        .collect())
}

/// Remove every rlord navigation binding, whatever key it is on.
pub fn unbind_nav_keys(bindings: &[(&str, &str)]) -> Result<()> {
    let mut keys = installed_nav_keys()?;
    keys.extend(bindings.iter().map(|(k, _)| k.to_string()));
    for key in keys {
        // Unbinding a key that isn't bound is not an error worth surfacing.
        let _ = run(&["unbind-key", "-n", &key]);
        let _ = run(&["unbind-key", "-T", PROFILE_TABLE, &key]);
    }
    Ok(())
}

/// Root-table keys currently bound to `rlord nav ...` on this server.
fn installed_nav_keys() -> Result<Vec<String>> {
    let out = match run(&["list-keys", "-T", "root"]) {
        Ok(o) => o,
        Err(_) => return Ok(vec![]), // no server: nothing installed
    };
    Ok(out
        .lines()
        .filter(|l| l.contains("rlord nav "))
        .filter_map(|l| l.split_whitespace().nth(3).map(str::to_string))
        .collect())
}

/// Record where the TUI lives so `nav home` can find it. Empty = "no home;
/// detach instead" (the TUI sets this when it attaches from outside tmux).
pub fn set_home(session: &str) -> Result<()> {
    run(&["set-option", "-g", HOME_OPTION, session])?;
    Ok(())
}

pub fn home() -> Option<String> {
    run(&["show-options", "-gqv", HOME_OPTION])
        .ok()
        .filter(|s| !s.is_empty())
}

/// Session of the pane this process runs in (valid inside tmux / run-shell).
pub fn current_session() -> Option<String> {
    if !inside_rlord() {
        return None;
    }
    run(&["display-message", "-p", "#{session_name}"])
        .ok()
        .filter(|s| !s.is_empty())
}

/// Flash a message on the current client's status line.
pub fn display_message(msg: &str) -> Result<()> {
    run(&["display-message", msg])?;
    Ok(())
}

pub fn switch_client(session: &str) -> Result<()> {
    run(&["switch-client", "-t", &exact(session)])?;
    Ok(())
}

pub fn detach_client() -> Result<()> {
    run(&["detach-client"])?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn user_client_is_most_recent() {
        let c = |n: &str, a| Client {
            name: n.into(),
            session: "s".into(),
            activity: a,
        };
        let clients = vec![c("/dev/ttys1", 10), c("/dev/ttys2", 20)];
        assert_eq!(user_client(&clients, None).unwrap().name, "/dev/ttys2");
        assert!(user_client(&[], None).is_none());
        // A terminal showing rlord beats a more recently active one that isn't.
        let mut clients = clients;
        clients[0].session = "rlord_01abc".into();
        assert_eq!(user_client(&clients, None).unwrap().name, "/dev/ttys1");
        clients[0].session = "home".into();
        assert_eq!(
            user_client(&clients, Some("home")).unwrap().name,
            "/dev/ttys1"
        );
    }

    #[test]
    fn quoting() {
        assert_eq!(shell_quote("abc-1.2/x"), "abc-1.2/x");
        assert_eq!(shell_quote("a b"), "'a b'");
        assert_eq!(shell_quote("it's"), r"'it'\''s'");
        assert_eq!(shell_quote(""), "''");
    }

    #[test]
    fn pane_command_shape() {
        let cmd = pane_command(
            &[("RLORD_SESSION_ID".into(), "abc".into())],
            &["claude".into(), "--session-id".into(), "u-1".into()],
        );
        assert_eq!(cmd, "exec env RLORD_SESSION_ID=abc claude --session-id u-1");
    }

    #[test]
    fn legacy_cleanup_only_matches_rlord_made_sessions() {
        let none = || String::new();
        assert!(is_legacy_rlord_session("rlord_overlord", none));
        assert!(is_legacy_rlord_session(
            "rlord_01m73sevvpr2xq5xd773z5abcd",
            none
        ));
        assert!(!is_legacy_rlord_session("rlord_notes", none));
        assert!(!is_legacy_rlord_session("rlord-rusty-gear", none));
        assert!(!is_legacy_rlord_session("work", none));
        assert!(is_legacy_rlord_session("rlord", || "zsh\nrlord\n".into()));
        assert!(!is_legacy_rlord_session("rlord", || "zsh\nvim\n".into()));
    }

    /// Real-tmux integration test of the actual module functions, on a
    /// private server socket. Gated: `RLORD_TMUX_TESTS=1 cargo test`.
    /// Serialized with a lock in case tests ever share the socket env.
    #[test]
    fn tmux_lifecycle_on_private_server() {
        if std::env::var("RLORD_TMUX_TESTS").as_deref() != Ok("1") {
            return;
        }
        // Safety: test process only; the daemon never sets this.
        std::env::set_var("RLORD_TMUX_SOCKET", "rlord-test");
        let _ = tmux_cmd().args(["kill-server"]).output();

        let name = "rlord_testsess";
        new_session(name, "/tmp", "sleep 30").unwrap();
        assert!(has_session(name));
        let (w, p) = window_pane_ids(name).unwrap();
        assert!(w.starts_with('@') && p.starts_with('%'));
        respawn_pane(name, "/tmp", "sleep 30").unwrap();
        kill_session(name).unwrap();
        assert!(!has_session(name));

        let _ = tmux_cmd().args(["kill-server"]).output();
    }
}
