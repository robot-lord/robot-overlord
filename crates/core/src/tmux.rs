pub fn kill_session(name: &str) -> Result<()> {
    if has_session(name) {
        run(&["kill-session", "-t", &exact(name)])?;
    }
    Ok(())
}

// ---- clients (the overlord moves the user's terminal around) ----

/// A terminal attached to the tmux server.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Client {
    pub name: String,
    pub session: String,
    /// Last input/output activity, epoch seconds.
    pub activity: i64,
}

pub fn list_clients() -> Vec<Client> {
    let Ok(out) = run(&[
        "list-clients",
        "-F",
        // Space-separated: none of the leading fields contain spaces; the
        // session name (which may) comes last.
        "#{client_activity} #{client_control_mode} #{client_name} #{session_name}",
    ]) else {
        return vec![]; // no server
    };
    out.lines()
        .filter_map(|l| {
            let mut f = l.splitn(4, ' ');
            let activity = f.next()?.parse().ok()?;
            if f.next()? == "1" {
                return None; // control-mode client (a program, not a person)
            }
            Some(Client {
                activity,
                name: f.next()?.to_string(),
                session: f.next()?.to_string(),
            })
        })
        .collect()
}

/// The user's terminal: the most recently active client that is showing
/// rlord (its home session or an rlord session), else the most recently
/// active client at all.
pub fn user_client<'a>(clients: &'a [Client], home: Option<&str>) -> Option<&'a Client> {
    let ours = |c: &&Client| {
        Some(c.session.as_str()) == home
            || c.session.ends_with("-rlord")
            || c.session.starts_with("rlord")
    };
    clients
        .iter()
        .filter(ours)
        .max_by_key(|c| c.activity)
        .or_else(|| clients.iter().max_by_key(|c| c.activity))
}

/// Point a specific client at a session.
pub fn switch_client_of(client: &str, session: &str) -> Result<()> {
    run(&["switch-client", "-c", client, "-t", &exact(session)])?;
    Ok(())
}

/// Mark a session visually: its own status-bar style and left label
/// (session-scoped options; other sessions keep the user's status bar).
pub fn style_session(session: &str, status_style: &str, status_left: &str) -> Result<()> {
    // `set-option -t =name` doesn't resolve on tmux 3.8; `=name:` does.
    let t = format!("{}:", exact(session));
    run(&["set-option", "-t", &t, "status", "on"])?;
    run(&["set-option", "-t", &t, "status-style", status_style])?;
    // Just the label: no window list, no clock/host on the right.
    run(&["set-option", "-t", &t, "status-right", ""])?;
    run(&["set-option", "-t", &t, "window-status-format", ""])?;
    run(&["set-option", "-t", &t, "window-status-current-format", ""])?;
    run(&["set-option", "-t", &t, "status-left", status_left])?;
    run(&["set-option", "-t", &t, "status-left-length", "40"])?;
    Ok(())
}

/// Name of the client this process runs under (valid inside tmux / run-shell).
pub fn current_client() -> Option<String> {
    if !inside_rlord() {
        return None;
    }
    run(&["display-message", "-p", "#{client_name}"])
        .ok()
        .filter(|s| !s.is_empty())
}

/// Open a popup on `client` running `cmd`, without waiting for it to close
/// (`display-popup` blocks until then). Closes any popup already open there.
/// `border` is a tmux style for the popup's border (`fg=#cba6f7`), `style`
/// the popup's own (`bg=#1d1828`; without it tmux paints the window style).
#[allow(clippy::too_many_arguments)]
pub fn open_popup(
    client: &str,
    width: &str,
    height: &str,
    title: &str,
    border: &str,
    style: &str,
    cmd: &str,
) -> Result<()> {
    let _ = close_popup(client);
    let mut child = tmux_cmd()
        .args([
            "display-popup",
            "-c",
            client,
            "-E",
            "-w",
            width,
            "-h",
            height,
            "-b",
            "rounded",
            "-S",
            border,
            "-s",
            style,
            "-T",
            title,
            cmd,
        ])
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .spawn()
        .context("running tmux")?;
    // Reap it whenever the popup closes.
    std::thread::spawn(move || {
        let _ = child.wait();
    });
    Ok(())
}

/// Close the popup on `client`, if any.
pub fn close_popup(client: &str) -> Result<()> {
    run(&["display-popup", "-C", "-c", client])?;
    Ok(())
}

// ---- embedding: another program draws a session's pane and types into it ----

/// The session's pane id (`%n`).
pub fn pane_id(session: &str) -> Result<String> {
    Ok(window_pane_ids(session)?.1)
}

/// Size the session's window to exactly `cols`×`rows` (the embedding view),
/// so the agent lays itself out for the space it is shown in.
pub fn resize_window(session: &str, cols: u16, rows: u16) -> Result<()> {
    let (window_id, _) = window_pane_ids(session)?;
    run(&[
        "resize-window",
        "-t",
        &window_id,
        "-x",
        &cols.to_string(),
        "-y",
        &rows.to_string(),
    ])?;
    Ok(())
}

/// Hand the window's size back to tmux. `resize-window` pins a window to
/// `window-size manual`; unsetting that lets it follow whichever terminal
/// views it (the server default, `latest`).
pub fn auto_size_window(session: &str) -> Result<()> {
    let (window_id, _) = window_pane_ids(session)?;
    // (`resize-window -A` would pin it to manual again — just unset.)
    run(&["set-option", "-w", "-u", "-t", &window_id, "window-size"])?;
    Ok(())
}

/// One frame of a pane: its visible rows with ANSI attributes (trailing
/// blank rows kept, so row indices match the cursor), plus the cursor.
pub struct PaneFrame {
    pub ansi: String,
    pub cursor_x: u16,
    pub cursor_y: u16,
    pub cursor_visible: bool,
    /// The pane is in a mode (copy mode): the screen and cursor are the
    /// mode's.
    pub in_mode: bool,
    /// Copy mode's selection, in its history-line coordinates
    /// `[start_x, start_y, end_x, end_y]` (tmux doesn't draw it into a
    /// capture): see `screen_selection`.
    pub selection: Option<[i64; 4]>,
    /// Copy mode's scroll position, the pane's live history size and its
    /// height.
    pub scroll: i64,
    pub history: i64,
    pub height: i64,
}

/// The pane's history size now (copy mode works on a snapshot of it taken
/// when the mode begins: record it then, see `screen_selection`).
pub fn history_size(pane: &str) -> Option<i64> {
    run(&["display-message", "-p", "-t", pane, "#{history_size}"])
        .ok()
        .and_then(|v| v.parse().ok())
}

/// The selection on screen, ends inclusive and in reading order:
/// ((col, row), (col, row)). Copy mode numbers lines in the snapshot it took
/// on entry, whose history size was `history_at_entry`: screen row 0 shows
/// line `history_at_entry - scroll`. (The live history size moves while the
/// agent prints; the snapshot doesn't.)
pub fn screen_selection(
    sel: [i64; 4],
    history_at_entry: i64,
    scroll: i64,
    h: i64,
) -> Option<((u16, u16), (u16, u16))> {
    let [sx, sy, ex, ey] = sel;
    let top = history_at_entry - scroll; // history line shown on screen row 0
    let a = (sy - top, sx);
    let b = (ey - top, ex);
    let ((r0, c0), (r1, c1)) = if a <= b { (a, b) } else { (b, a) };
    if r1 < 0 || r0 >= h {
        return None;
    }
    // Clipped to the screen: a part above starts at the top-left.
    let (r0, c0) = if r0 < 0 { (0, 0) } else { (r0, c0) };
    let (r1, c1) = if r1 >= h {
        (h - 1, i64::from(u16::MAX))
    } else {
        (r1, c1)
    };
    let u = |v: i64| v.clamp(0, i64::from(u16::MAX)) as u16;
    Some(((u(c0), u(r0)), (u(c1), u(r1))))
}

pub fn capture_frame(pane: &str) -> Result<PaneFrame> {
    // One tmux invocation for both: the cursor line, then the screen.
    let out = tmux_cmd()
        .args([
            "display-message",
            "-p",
            "-t",
            pane,
            // In copy mode: its cursor, and (-M) its screen with the
            // selection.
            "#{?pane_in_mode,#{copy_cursor_x},#{cursor_x}} \
             #{?pane_in_mode,#{copy_cursor_y},#{cursor_y}} \
             #{?pane_in_mode,1,#{cursor_flag}} #{pane_in_mode} \
             #{?selection_present,#{selection_start_x}#,#{selection_start_y}#,\
             #{selection_end_x}#,#{selection_end_y},-} \
             #{?pane_in_mode,#{scroll_position},0} #{history_size} #{pane_height}",
            ";",
            "capture-pane",
            "-p",
            "-e",
            "-M",
            "-t",
            pane,
        ])
        .output()
        .context("running tmux")?;
    if !out.status.success() {
        bail!(
            "tmux capture failed: {}",
            String::from_utf8_lossy(&out.stderr).trim()
        );
    }
    let text = String::from_utf8_lossy(&out.stdout);
    let (head, ansi) = text.split_once('\n').unwrap_or((&text, ""));
    let fields: Vec<&str> = head.split_whitespace().collect();
    let num = |i: usize| -> i64 { fields.get(i).and_then(|v| v.parse().ok()).unwrap_or(0) };
    let mut f = fields.iter().map(|v| v.parse::<u16>().unwrap_or(0));
    Ok(PaneFrame {
        cursor_x: f.next().unwrap_or(0),
        cursor_y: f.next().unwrap_or(0),
        cursor_visible: f.next().unwrap_or(0) == 1,
        in_mode: f.next().unwrap_or(0) == 1,
        selection: fields.get(4).and_then(|f| {
            let n: Vec<i64> = f
                .split(',')
                .map(|v| v.parse().ok())
                .collect::<Option<_>>()?;
            n.try_into().ok()
        }),
        scroll: num(5),
        history: num(6),
        height: num(7),
        ansi: ansi.to_string(),
    })
}

/// Leave copy mode (or any mode) if the pane is in one.
