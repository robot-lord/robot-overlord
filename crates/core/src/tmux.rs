//! tmux supervision. rlord runs its **own tmux server** (`tmux -L rlord`)
//! with a generated config (no status bar, no prefix, only rlord's keys): the
//! user's personal tmux is never touched, and tmux is an implementation
//! detail they don't see. One tmux session per rlord session; its agent runs
//! in one pane, pinned by id (`@rlord_pane`) — with the user's tmux profile
//! on (tmux_profile.rs) the user may add splits and windows around it. Session names are Docker-style `rlord-<adjective>-<noun>`
//! (names.rs), minted once and stored; never derived from the display name. `remain-on-exit` is set so an exited agent leaves a dead
//! pane (restartable in place via `respawn-pane -k`) instead of tearing the
//! tmux session down.
//!
//! Targeting rule: windows and panes are addressed by their unique tmux ids
//! (`@n`/`%n`, resolved via `list-panes`), NEVER by index — the user's tmux
//! config may set base-index/pane-base-index and shift all numbering (this
//! bit us on first contact with a real config).

use std::process::Command;

use anyhow::{bail, Context, Result};

/// tmux target for exact session-name match (`=` disables prefix matching).
fn exact(name: &str) -> String {
    format!("={name}")
}

/// Socket name of rlord's private tmux server (`tmux -L <name>`). Tests
/// override it with `RLORD_TMUX_SOCKET`.
pub fn socket_name() -> String {
    std::env::var("RLORD_TMUX_SOCKET")
        .ok()
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "rlord".to_string())
}

/// Config the private server starts with (written next to the database).
pub fn conf_path() -> std::path::PathBuf {
    crate::paths::data_dir().join("tmux.conf")
}

const CONF: &str = r#"# Generated by rlord — the config of rlord's private tmux server.
# Regenerated on every start; put your own tweaks in tmux.local.conf beside it.
set -g status off
set -g prefix None
set -g prefix2 None
unbind-key -a -T prefix
set -g escape-time 10
set -g history-limit 50000
set -g focus-events on
set -g extended-keys on
set -g default-terminal "tmux-256color"
set -as terminal-features ",*:RGB"
set -as terminal-features ",xterm*:extkeys"
set -g set-titles on
set -g set-titles-string '#S'
set -g detach-on-destroy on
"#;

/// Write the server config (cheap; idempotent).
pub fn write_conf() -> Result<()> {
    let p = conf_path();
    if let Some(d) = p.parent() {
        std::fs::create_dir_all(d)?;
    }
    let local = p.with_file_name("tmux.local.conf");
    let mut conf = CONF.to_string();
    // `[tmux] mouse` (on unless turned off; unreadable config: on).
    let mouse = crate::config::Config::load().map_or(true, |c| c.tmux.mouse);
    conf.push_str(if mouse {
        "set -g mouse on\n"
    } else {
        "set -g mouse off\n"
    });
    // The user's imported tmux profile: its bindings live in tables only
    // sessions with the profile on can reach (see tmux_profile.rs).
    let profile = crate::tmux_profile::keys_path();
    if profile.exists() {
        conf.push_str(&format!(
            "source-file -q {}\n",
            shell_quote(&profile.to_string_lossy())
        ));
    }
    if local.exists() {
        conf.push_str(&format!(
            "source-file {}\n",
            shell_quote(&local.to_string_lossy())
        ));
    }
    if std::fs::read_to_string(&p).ok().as_deref() != Some(conf.as_str()) {
        std::fs::write(&p, conf)?;
    }
    Ok(())
}

/// Kill rlord's whole tmux server (every session in it).
pub fn kill_server() -> Result<()> {
    let _ = run(&["kill-server"]); // "no server running" is fine
    Ok(())
}

/// Re-apply the generated config to a running server.
pub fn source_conf() -> Result<()> {
    write_conf()?;
    let p = conf_path();
    run(&["source-file", &p.to_string_lossy()])?;
    Ok(())
}

/// Restart the program in a session's pane (`respawn-pane -k`).
pub fn respawn_plain(session: &str, cmd: &str) -> Result<()> {
    let (_, pane) = window_pane_ids(session)?;
    run(&["respawn-pane", "-k", "-t", &pane, cmd])?;
    Ok(())
}

/// Whether a session on the user's default server is one an older rlord
/// made: `rlord_overlord`, `rlord_<session id>` (26-char lowercase ULID), or
/// the home session `rlord` while it is actually running rlord. A personal
/// session that merely has a similar name is left alone.
fn is_legacy_rlord_session(name: &str, pane_commands: impl FnOnce() -> String) -> bool {
    if name == "rlord" {
        return pane_commands().lines().any(|c| c.trim() == "rlord");
    }
    match name.strip_prefix("rlord_") {
        Some("overlord") => true,
        Some(id) => {
            id.len() == 26
                && id
                    .chars()
                    .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit())
        }
        None => false,
    }
}

/// Remove what older rlord versions left on the user's **default** tmux
/// server: the sessions it made (see `is_legacy_rlord_session`) and rlord's
/// root-table key bindings. Returns the session names killed.
pub fn cleanup_default_server() -> Vec<String> {
    // Only the real install has legacy state there; a test/alternate
    // server must never reach into the user's default tmux.
    if socket_name() != "rlord" {
        return vec![];
    }
    let tmux = |args: &[&str]| {
        Command::new("tmux")
            .env_remove("TMUX")
            .args(args)
            .output()
            .ok()
            .filter(|o| o.status.success())
            .map(|o| String::from_utf8_lossy(&o.stdout).to_string())
    };
    let mut killed = Vec::new();
    for name in tmux(&["list-sessions", "-F", "#{session_name}"])
        .unwrap_or_default()
        .lines()
    {
        let panes = || {
            tmux(&[
                "list-panes",
                "-s",
                "-t",
                &exact(name),
                "-F",
                "#{pane_current_command}",
            ])
            .unwrap_or_default()
        };
        if is_legacy_rlord_session(name, panes)
            && tmux(&["kill-session", "-t", &exact(name)]).is_some()
        {
            killed.push(name.to_string());
        }
    }
    for line in tmux(&["list-keys", "-T", "root"])
        .unwrap_or_default()
        .lines()
    {
        if line.contains("rlord nav ") {
            if let Some(key) = line.split_whitespace().nth(3) {
                tmux(&["unbind-key", "-n", key]);
            }
        }
    }
    killed
}

/// A `tmux` command aimed at rlord's server (used for exec'ing attach).
pub fn command() -> Command {
    tmux_cmd()
}

/// Whether this process runs inside rlord's tmux server (as opposed to
/// outside tmux, or inside the user's own tmux).
pub fn inside_rlord() -> bool {
    let Some(t) = std::env::var_os("TMUX") else {
        return false;
    };
    let t = t.to_string_lossy();
    let sock = t.split(',').next().unwrap_or("");
    std::path::Path::new(sock)
        .file_name()
        .is_some_and(|n| n.to_string_lossy() == socket_name())
}

fn tmux_cmd() -> Command {
    static CONF_WRITTEN: std::sync::Once = std::sync::Once::new();
    CONF_WRITTEN.call_once(|| {
        if let Err(e) = write_conf() {
            tracing::warn!(error = %e, "writing rlord tmux.conf");
        }
    });
    let mut c = Command::new("tmux");
    // Inside rlord's server, TMUX tells tmux which client/pane "current"
    // means; anywhere else it would point at the user's own tmux.
    if !inside_rlord() {
        c.env_remove("TMUX");
        // A pane id from another server: never let it reach rlord's server
        // (a server started from here would keep it in its environment).
        c.env_remove("TMUX_PANE");
    }
    c.args(["-L", &socket_name(), "-f"]);
    c.arg(conf_path());
    // Without a UTF-8 locale (e.g. the daemon under launchd, which starts
    // with no LANG) tmux rewrites tabs and non-ASCII in its output to `_`:
    // parsing breaks and captured screens are mangled.
    let utf8 = ["LC_ALL", "LC_CTYPE", "LANG"]
        .iter()
        .find_map(|k| std::env::var(k).ok().filter(|v| !v.is_empty()))
        .is_some_and(|v| v.to_ascii_uppercase().replace('-', "").contains("UTF8"));
    if !utf8 {
        // C.UTF-8 is the one UTF-8 locale every glibc/musl Linux has; macOS
        // has no C.UTF-8 but always en_US.UTF-8.
        let locale = if cfg!(target_os = "macos") {
            "en_US.UTF-8"
        } else {
            "C.UTF-8"
        };
        c.env("LC_CTYPE", locale);
    }
    c
}

fn run(args: &[&str]) -> Result<String> {
    let out = tmux_cmd()
        .args(args)
        .output()
        .context("running tmux (is tmux installed?)")?;
    if !out.status.success() {
        bail!(
            "tmux {} failed: {}",
            args.first().unwrap_or(&"?"),
            String::from_utf8_lossy(&out.stderr).trim()
        );
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

/// Rename a tmux session in place (attached clients stay attached).
pub fn rename_session(old: &str, new: &str) -> Result<()> {
    run(&["rename-session", "-t", &exact(old), new])?;
    Ok(())
}

pub fn has_session(name: &str) -> bool {
    tmux_cmd()
        .args(["has-session", "-t", &exact(name)])
        .output()
        .map(|o| o.status.success())
        .unwrap_or(false)
}

/// Session option naming the agent's pane. With the user's tmux profile a
/// session can have splits and windows, and the agent's pane isn't
/// necessarily listed first (`split-window -b` puts the new one ahead).
const AGENT_PANE: &str = "@rlord_pane";

/// Resolve the session's agent window and pane to their unique tmux ids:
/// the pinned pane if it is still there, else the first one.
/// Name the agent's window after the session (`label`) and stop tmux from
/// renaming it after the running program; Claude Code's process shows up
/// as its version number (`2.1.322`).
pub fn name_agent_window(name: &str, label: &str) -> Result<()> {
    let (window_id, _) = window_pane_ids(name)?;
    run(&["rename-window", "-t", &window_id, label])?;
    run(&[
        "set-option",
        "-w",
        "-t",
        &window_id,
        "automatic-rename",
        "off",
    ])?;
    Ok(())
}

fn window_pane_ids(name: &str) -> Result<(String, String)> {
    let out = run(&[
        "list-panes",
        "-s",
        "-t",
        &exact(name),
        "-F",
        &format!("#{{window_id}} #{{pane_id}} #{{{AGENT_PANE}}}"),
    ])?;
    let panes: Vec<(&str, &str, &str)> = out
        .lines()
        .filter_map(|l| {
            let mut f = l.splitn(3, ' ');
            Some((f.next()?, f.next()?, f.next().unwrap_or("")))
        })
        .collect();
    let (w, p, _) = panes
        .iter()
        .find(|(_, p, pinned)| p == pinned)
        .or_else(|| panes.first())
        .context("session has no panes")?;
    Ok((w.to_string(), p.to_string()))
}

/// Record the session's current agent pane (first pane, if none recorded).
fn pin_agent_pane(name: &str) -> Result<()> {
    let (_, pane) = window_pane_ids(name)?;
    run(&[
        "set-option",
        "-t",
        &format!("{}:", exact(name)),
        AGENT_PANE,
        &pane,
    ])?;
    Ok(())
}

/// POSIX single-quote escaping.
pub fn shell_quote(s: &str) -> String {
    if !s.is_empty()
        && s.chars()
            .all(|c| c.is_ascii_alphanumeric() || "-_./=:@%+,".contains(c))
    {
        s.to_string()
    } else {
        format!("'{}'", s.replace('\'', r"'\''"))
    }
}

/// Build the pane command: `exec env K=V... argv...`, fully quoted. Env is
/// embedded in the command (rather than tmux session env) so respawns are
/// deterministic and the vars reach hook subprocesses.
pub fn pane_command(env: &[(String, String)], argv: &[String]) -> String {
    let mut parts = vec!["exec".to_string(), "env".to_string()];
    for (k, v) in env {
        parts.push(shell_quote(&format!("{k}={v}")));
    }
    parts.extend(argv.iter().map(|a| shell_quote(a)));
    parts.join(" ")
}

pub fn new_session(name: &str, cwd: &str, pane_cmd: &str) -> Result<()> {
    run(&["new-session", "-d", "-s", name, "-c", cwd, pane_cmd])?;
    // Dead pane instead of dead session when the agent exits. If this
    // follow-up fails, tear the half-made session down rather than leaking it.
    let configure = || -> Result<()> {
        pin_agent_pane(name)?;
        keep_agent_pane_on_exit(name)?;
        Ok(())
    };
    if let Err(e) = configure() {
        let _ = kill_session(name);
        return Err(e);
    }
    Ok(())
}

/// The agent's pane stays (dead) when the agent exits, so rlord can show it
/// stopped and restart it: `remain-on-exit` on that pane only. Panes the
/// user splits off close normally when their program exits. (Older rlord set
/// it on the whole window: that is undone here.) Idempotent.
pub fn keep_agent_pane_on_exit(session: &str) -> Result<()> {
    let (window_id, pane_id) = window_pane_ids(session)?;
    run(&["set-option", "-p", "-t", &pane_id, "remain-on-exit", "on"])?;
    run(&["set-option", "-wu", "-t", &window_id, "remain-on-exit"])?;
    Ok(())
}

/// A detached session with no rlord pane conventions (used for the TUI's
/// home session).
pub fn new_plain_session(name: &str, cwd: &str, cmd: &str) -> Result<()> {
    run(&["new-session", "-d", "-s", name, "-c", cwd, cmd])?;
    Ok(())
}

pub fn respawn_pane(name: &str, cwd: &str, pane_cmd: &str) -> Result<()> {
    let (_, pane_id) = window_pane_ids(name)?;
    run(&["respawn-pane", "-k", "-c", cwd, "-t", &pane_id, pane_cmd])?;
    Ok(())
}

