//! Transcripts in one shape, whichever agent wrote them.
//!
//! Claude Code and Codex keep a conversation as JSON lines, each in its own
//! format. `Format::line` reads one line as a `Line`, and a `Line` answers
//! the questions rlord asks of a transcript: is this a message (who said
//! what, when), a prompt the human typed, the agent's reply, a title, token
//! usage, the model, the end of a turn. Everything that reads transcripts
//! (triage excerpts, token stats, history search and read, archive
//! summaries, the observed model) goes through it, so a new agent that
//! keeps JSON lines needs a line reader and nothing else.
//!
//! The seam for consumers is this module's functions and their results
//! (`Excerpts`, `TranscriptStats`, `context_tokens`, `observed_model`,
//! `working`; `history::search`/`read` for messages), not `Line`: an agent
//! whose conversations aren't a JSONL file gets a `Format` that those
//! functions answer without going through lines. OpenCode is one: its
//! conversations are rows in its database, named by a path that isn't a
//! file (`opencode::locate`), and each function here asks `opencode` first.

use std::path::{Path, PathBuf};

use serde_json::Value;

use super::{claude, codex, opencode};

/// Whose transcript format a file is in.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Format {
    Claude,
    Codex,
    /// Not lines: a conversation in OpenCode's database.
    OpenCode,
}

impl Format {
    /// From the file's name: Codex writes `rollout-<time>-<id>.jsonl`,
    /// Claude Code `<id>.jsonl` (and `agent-<id>.jsonl` for sub-agents);
    /// an OpenCode conversation is `<opencode.db>/<ses_…>`.
    pub fn of(path: &Path) -> Format {
        let name = path.file_name().map(|n| n.to_string_lossy());
        if opencode::is_transcript(path) {
            Format::OpenCode
        } else if name.is_some_and(|n| n.starts_with("rollout-")) {
            Format::Codex
        } else {
            Format::Claude
        }
    }

    pub fn line(self, v: &Value) -> Line<'_> {
        Line { format: self, v }
    }
}

/// A conversation's title, and who gave it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Title {
    /// Set by the user: wins.
    User(String),
    /// Generated by the agent.
    Generated(String),
}

/// Token usage reported on a line.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct Usage {
    pub input: i64,
    pub output: i64,
    /// The whole context sent with that request.
    pub context: u64,
    /// `input`/`output` are the conversation's running totals (Codex), not
    /// this one request's (Claude).
    pub cumulative: bool,
}

/// One transcript line, read in its agent's format.
#[derive(Clone, Copy)]
pub struct Line<'a> {
    format: Format,
    v: &'a Value,
}

impl<'a> Line<'a> {
    /// When it was written (ISO-8601, as the agent wrote it).
    pub fn at(&self) -> Option<&'a str> {
        self.v["timestamp"].as_str()
    }

    /// A conversation message: who (`you`, `agent`, `tool`) and its text.
    /// Tool calls read as `[tool] main argument`. None for lines that
    /// aren't conversation (titles, settings, injected context).
    pub fn message(&self) -> Option<(&'static str, String)> {
        match self.format {
            Format::Claude => claude::message(self.v),
            Format::Codex => codex::message(self.v),
            // (Never lines: see `Format::OpenCode`.)
            Format::OpenCode => None,
        }
    }

    /// A prompt the human typed (not tool results, injected context or
    /// command wrappers).
    pub fn prompt(&self) -> Option<String> {
        match self.format {
            Format::Claude => claude::human_prompt(self.v),
            Format::Codex => codex::human_prompt(self.v),
            // (Never lines: see `Format::OpenCode`.)
            Format::OpenCode => None,
        }
    }

    /// The text the agent answered with.
    pub fn reply(&self) -> Option<String> {
        match self.format {
            Format::Claude => claude::reply_text(self.v),
            Format::Codex => codex::reply_text(self.v),
            // (Never lines: see `Format::OpenCode`.)
            Format::OpenCode => None,
        }
    }

    pub fn title(&self) -> Option<Title> {
        match self.format {
            Format::Claude => claude::title(self.v),
            Format::Codex => codex::title(self.v),
            // (Never lines: see `Format::OpenCode`.)
            Format::OpenCode => None,
        }
    }

    /// The agent's own record of the latest prompt (Claude writes one; it
    /// survives when tool output pushes the prompt out of the tail).
    pub fn last_prompt(&self) -> Option<&'a str> {
        match self.format {
            Format::Claude => claude::last_prompt(self.v),
            Format::Codex | Format::OpenCode => None,
        }
    }

    pub fn usage(&self) -> Option<Usage> {
        match self.format {
            Format::Claude => claude::usage(self.v),
            Format::Codex => codex::usage(self.v),
            // (Never lines: see `Format::OpenCode`.)
            Format::OpenCode => None,
        }
    }

    /// The model that line ran on.
    pub fn model(&self) -> Option<&'a str> {
        match self.format {
            Format::Claude => claude::model(self.v),
            Format::Codex => codex::model(self.v),
            // (Never lines: see `Format::OpenCode`.)
            Format::OpenCode => None,
        }
    }

    /// `Some(true)`: this line ends the agent's turn (a final reply).
    /// `Some(false)`: it opens or continues one. None: says nothing.
    pub fn turn_ended(&self) -> Option<bool> {
        match self.format {
            Format::Claude => claude::turn_ended(self.v),
            Format::Codex => codex::turn_ended(self.v),
            // (Never lines: see `Format::OpenCode`.)
            Format::OpenCode => None,
        }
    }
}

/// Parse ISO-8601 `2026-10-27T17:03:44.498Z` to ms epoch (lenient).
pub fn parse_iso_ms(s: &str) -> Option<i64> {
    let (date, rest) = s.split_once('T')?;
    let mut d = date.split('-').map(|x| x.parse::<i64>().ok());
    let (y, m, day) = (d.next()??, d.next()??, d.next()??);
    let time = rest.trim_end_matches('Z');
    let mut t = time.split(':');
    let h: i64 = t.next()?.parse().ok()?;
    let mi: i64 = t.next()?.parse().ok()?;
    let sec: f64 = t.next()?.parse().ok()?;
    // days from civil (Howard Hinnant)
    let (y2, m2) = if m <= 2 { (y - 1, m + 9) } else { (y, m - 3) };
    let era = y2.div_euclid(400);
    let yoe = y2 - era * 400;
    let doy = (153 * m2 + 2) / 5 + day - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    let days = era * 146097 + doe - 719468;
    Some(days * 86_400_000 + h * 3_600_000 + mi * 60_000 + (sec * 1000.0) as i64)
}

/// What a session is about, read cheaply from its transcript (no AI): the
/// prompt that started it, the latest real prompt, the latest reply text,
/// and the conversation's title. For the overlord's triage.
#[derive(Debug, Default, Clone, PartialEq, Eq, serde::Serialize)]
pub struct Excerpts {
    pub first_prompt: Option<String>,
    pub last_prompt: Option<String>,
    pub last_reply: Option<String>,
    pub title: Option<String>,
}

/// Bytes read from each end of a transcript; they can be many MB.
const EXCERPT_WINDOW: u64 = 256 * 1024;

pub(crate) fn read_window(path: &Path, from_end: bool) -> Option<String> {
    use std::io::{Read, Seek, SeekFrom};
    let mut f = std::fs::File::open(path).ok()?;
    let len = f.metadata().ok()?.len();
    let start = if from_end {
        len.saturating_sub(EXCERPT_WINDOW)
    } else {
        0
    };
    f.seek(SeekFrom::Start(start)).ok()?;
    let mut buf = Vec::new();
    f.take(EXCERPT_WINDOW).read_to_end(&mut buf).ok()?;
    let text = String::from_utf8_lossy(&buf).into_owned();
    // A tail window starts mid-line: drop the partial first line.
    Some(if start > 0 {
        text.split_once('\n')
            .map(|(_, r)| r.to_string())
            .unwrap_or_default()
    } else {
        text
    })
}

pub fn clip(s: &str, max: usize) -> String {
    let s = s.split_whitespace().collect::<Vec<_>>().join(" ");
    if s.chars().count() <= max {
        s
    } else {
        format!("{}…", s.chars().take(max).collect::<String>())
    }
}

/// Whether a transcript is there to read (a file; or, for OpenCode, the
/// conversation in its database).
pub fn exists(path: &Path) -> bool {
    match opencode::locate(path) {
        Some((db, id)) => opencode::exists(db, id) == Some(true),
        None => path.exists(),
    }
}

pub fn transcript_excerpts(path: &Path) -> Excerpts {
    if let Some((db, id)) = opencode::locate(path) {
        return opencode::excerpts(db, id);
    }
    let (head, tail) = read_head_tail(path);
    excerpts_from(Format::of(path), &head, &tail)
}

/// Parsed JSON lines from the start and the end of a transcript (each at
/// most `EXCERPT_WINDOW` bytes; a small file is read once and used for both).
pub fn read_head_tail(path: &Path) -> (Vec<Value>, Vec<Value>) {
    let parse = |s: String| -> Vec<Value> {
        s.lines()
            .filter_map(|l| serde_json::from_str(l).ok())
            .collect()
    };
    let head = read_window(path, false).map(parse).unwrap_or_default();
    let small = std::fs::metadata(path).is_ok_and(|m| m.len() <= EXCERPT_WINDOW);
    let tail = if small {
        head.clone()
    } else {
        read_window(path, true).map(parse).unwrap_or_default()
    };
    (head, tail)
}

pub fn excerpts_from(format: Format, head: &[Value], tail: &[Value]) -> Excerpts {
    let prompt = |v: &Value| format.line(v).prompt();
    let mut e = Excerpts {
        first_prompt: head.iter().find_map(prompt).map(|t| clip(&t, 300)),
        ..Default::default()
    };
    for v in tail.iter().rev() {
        let l = format.line(v);
        if e.last_prompt.is_none() {
            e.last_prompt = l.prompt().map(|t| clip(&t, 300));
        }
        if e.last_reply.is_none() {
            e.last_reply = l.reply().map(|t| clip(&t, 500));
        }
        // A title the user set wins over the one the agent generated.
        if e.title.is_none() {
            if let Some(Title::User(t)) = l.title() {
                e.title = Some(t);
            }
        }
        if e.last_prompt.is_some() && e.last_reply.is_some() && e.title.is_some() {
            break;
        }
    }
    if e.title.is_none() {
        e.title = tail
            .iter()
            .rev()
            .find_map(|v| match format.line(v).title() {
                Some(Title::Generated(t)) if !t.trim().is_empty() => Some(clip(&t, 120)),
                _ => None,
            });
    }
    // Long tool-heavy turns push the last typed prompt out of the tail
    // window; Claude also records it in `last-prompt` entries.
    if e.last_prompt.is_none() {
        e.last_prompt = tail
            .iter()
            .rev()
            .find_map(|v| format.line(v).last_prompt())
            .filter(|t| !t.trim().is_empty())
            .map(|t| clip(t, 300));
    }
    // One prompt so far: don't repeat it. Claude's `last-prompt` record may
    // be a truncated copy ("…"), so a clipped one matches by prefix; an
    // unclipped one must match exactly (a short "continue" is a new prompt).
    if let (Some(l), Some(f)) = (&e.last_prompt, &e.first_prompt) {
        let same = match l.strip_suffix('…') {
            Some(clipped) => f.starts_with(clipped),
            None => l == f,
        };
        if same {
            e.last_prompt = None;
        }
    }
    e
}

/// The conversation's size in tokens, from its last reported usage (the
/// whole context it sent); else a guess from the file size.
pub fn context_tokens(path: &Path) -> u64 {
    if let Some((db, id)) = opencode::locate(path) {
        return opencode::context_tokens(db, id);
    }
    let format = Format::of(path);
    let (_, tail) = read_head_tail(path);
    tail.iter()
        .rev()
        .find_map(|v| format.line(v).usage())
        .map(|u| u.context)
        .unwrap_or_else(|| std::fs::metadata(path).map(|m| m.len() / 4).unwrap_or(0))
}

/// The model of the latest turn in a transcript, reading only its tail.
pub fn observed_model(path: &Path) -> Option<String> {
    if let Some((db, id)) = opencode::locate(path) {
        return opencode::observed_model(db, id);
    }
    let format = Format::of(path);
    let (_, tail) = read_head_tail(path);
    tail.iter()
        .rev()
        .find_map(|v| format.line(v).model().map(str::to_string))
}

/// Whether the agent is mid-turn (`Some(true)` working, `Some(false)` its
/// turn is over), from the turn lines read so far. Incremental (see
/// `transcript_stats`): polling it costs only what was appended. None when
/// no turn line has been read: there has been no turn yet, or (a daemon
/// restart mid-turn) it began before what was read this run.
pub fn working(path: &Path) -> Option<bool> {
    let st = transcript_stats(path)?;
    match (st.ended, st.turn_seen) {
        (true, _) => Some(false),
        (false, true) => Some(true),
        (false, false) => None,
    }
}

/// Token totals and time span from a transcript.
///
/// Incremental: a running agent's transcript is polled again and again while
/// it grows, so the totals so far and the offset read up to are kept per
/// file, and each call parses only the bytes appended since. A trailing line
/// without its newline counts once it parses as complete JSON. A file that
/// was replaced (new inode) or shrank is read again from the start.
pub fn transcript_stats(path: &Path) -> Option<TranscriptStats> {
    // (OpenCode keeps the totals itself: one row, nothing to remember.)
    if let Some((db, id)) = opencode::locate(path) {
        return opencode::stats(db, id);
    }
    use std::io::{Read, Seek, SeekFrom};
    use std::os::unix::fs::MetadataExt;
    let format = Format::of(path);
    let meta = std::fs::metadata(path).ok()?;
    let (len, ino) = (meta.len(), meta.ino());
    let modified = meta.modified().ok();
    // Copy the cursor out: the (possibly large) read happens unlocked, so one
    // slow file never holds up stats for another.
    let mut c = {
        let cursors = STATS_CURSORS.lock().unwrap_or_else(|e| e.into_inner());
        cursors.get(path).cloned().unwrap_or_default()
    };
    let before = (c.ino, c.offset);
    if c.ino != ino || len < c.offset {
        c = StatsCursor {
            ino,
            ..Default::default()
        };
    }
    if len > c.offset {
        let mut f = std::fs::File::open(path).ok()?;
        f.seek(SeekFrom::Start(c.offset)).ok()?;
        let mut buf = Vec::with_capacity((len - c.offset) as usize);
        f.take(len - c.offset).read_to_end(&mut buf).ok()?;
        // Complete lines, plus a trailing one if it is already whole JSON
        // (a final record may never get its newline).
        let mut end = buf.iter().rposition(|&b| b == b'\n').map_or(0, |e| e + 1);
        let tail = &buf[end..];
        if !tail.is_empty() && serde_json::from_slice::<Value>(tail).is_ok() {
            end = buf.len();
        }
        for line in buf[..end].split(|&b| b == b'\n') {
            let Ok(v) = serde_json::from_slice::<Value>(line) else {
                continue;
            };
            let l = format.line(&v);
            if let Some(ts) = l.at().and_then(parse_iso_ms) {
                c.first.get_or_insert(ts);
                c.last = Some(ts);
            }
            match l.usage() {
                Some(u) if u.cumulative => (c.input, c.output) = (u.input, u.output),
                Some(u) => {
                    c.input += u.input;
                    c.output += u.output;
                }
                None => {}
            }
            // Done when the latest turn is a final reply (no tool call
            // pending); a tool result or new prompt reopens it.
            if let Some(ended) = l.turn_ended() {
                c.ended = ended;
                c.turn_seen = true;
            }
        }
        c.offset += end as u64;
    }
    let mut stats = c.stats();
    stats.modified = modified;
    c.used = std::time::Instant::now();
    if (c.ino, c.offset) != before {
        c.dirty = true;
    }
    let mut cursors = STATS_CURSORS.lock().unwrap_or_else(|e| e.into_inner());
    cursors.insert(path.to_path_buf(), c);
    // Bounded: forget the least recently used files past the cap.
    if cursors.len() > STATS_CURSOR_CAP {
        let mut by_age: Vec<(std::time::Instant, PathBuf)> =
            cursors.iter().map(|(p, c)| (c.used, p.clone())).collect();
        by_age.sort();
        for (_, p) in by_age.into_iter().take(cursors.len() - STATS_CURSOR_CAP) {
            cursors.remove(&p);
        }
    }
    Some(stats)
}

/// What `transcript_stats` knows about a transcript.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct TranscriptStats {
    pub input_tokens: i64,
    pub output_tokens: i64,
    pub first: Option<i64>,
    pub last: Option<i64>,
    /// The latest turn is a final reply: the agent finished.
    pub ended: bool,
    /// A line that opens or ends a turn has been read (so `ended: false`
    /// means "mid-turn", not "nothing known").
    pub turn_seen: bool,
    /// When the file was last written.
    pub modified: Option<std::time::SystemTime>,
}

/// How far `transcript_stats` has read a file, and the totals so far.
#[derive(Clone)]
struct StatsCursor {
    /// Moved since last saved (`take_dirty_cursors`).
    dirty: bool,
    ended: bool,
    turn_seen: bool,
    ino: u64,
    offset: u64,
    input: i64,
    output: i64,
    first: Option<i64>,
    last: Option<i64>,
    used: std::time::Instant,
}

impl Default for StatsCursor {
    fn default() -> Self {
        StatsCursor {
            dirty: false,
            ended: false,
            turn_seen: false,
            ino: 0,
            offset: 0,
            input: 0,
            output: 0,
            first: None,
            last: None,
            used: std::time::Instant::now(),
        }
    }
}

impl StatsCursor {
    fn stats(&self) -> TranscriptStats {
        TranscriptStats {
            input_tokens: self.input,
            output_tokens: self.output,
            first: self.first,
            last: self.last,
            ended: self.ended,
            turn_seen: self.turn_seen,
            modified: None,
        }
    }
}

/// A transcript's read position and totals, as saved in the DB so a
/// restarted daemon reads forward instead of from the start.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct CursorState {
    pub ino: u64,
    pub offset: u64,
    pub input_tokens: i64,
    pub output_tokens: i64,
    pub first: Option<i64>,
    pub last: Option<i64>,
    pub ended: bool,
}

/// Bump when `transcript_stats` counts differently: saved positions from an
/// older version are dropped and their transcripts recounted.
pub const STATS_PARSE_VERSION: i64 = 1;

/// How many saved positions are loaded at startup (the most recent).
pub const STATS_CURSOR_SEED: usize = STATS_CURSOR_CAP;

/// Load saved positions (daemon start). Files already read this run keep
/// their in-memory position.
pub fn seed_cursors(saved: Vec<(PathBuf, CursorState)>) {
    let mut cursors = STATS_CURSORS.lock().unwrap_or_else(|e| e.into_inner());
    for (path, st) in saved {
        cursors.entry(path).or_insert_with(|| StatsCursor {
            ino: st.ino,
            offset: st.offset,
            input: st.input_tokens,
            output: st.output_tokens,
            first: st.first,
            last: st.last,
            ended: st.ended,
            // (Not saved: an ended turn was certainly seen; an open one
            // may have begun before this run.)
            turn_seen: st.ended,
            ..Default::default()
        });
    }
}

/// Positions that moved since the last call, to save.
pub fn take_dirty_cursors() -> Vec<(PathBuf, CursorState)> {
    let mut cursors = STATS_CURSORS.lock().unwrap_or_else(|e| e.into_inner());
    cursors
        .iter_mut()
        .filter(|(_, c)| c.dirty)
        .map(|(p, c)| {
            c.dirty = false;
            (
                p.clone(),
                CursorState {
                    ino: c.ino,
                    offset: c.offset,
                    input_tokens: c.input,
                    output_tokens: c.output,
                    first: c.first,
                    last: c.last,
                    ended: c.ended,
                },
            )
        })
        .collect()
}

/// Forget every position: the next reads start from the top (`--rescan`).
pub fn clear_cursors() {
    STATS_CURSORS
        .lock()
        .unwrap_or_else(|e| e.into_inner())
        .clear();
}

/// Transcripts whose read position is remembered (most recently used).
const STATS_CURSOR_CAP: usize = 1000;

static STATS_CURSORS: std::sync::LazyLock<
    std::sync::Mutex<std::collections::HashMap<PathBuf, StatsCursor>>,
> = std::sync::LazyLock::new(Default::default);

