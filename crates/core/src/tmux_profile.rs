//! Your tmux, inside rlord: an opt-in, per-session **profile** imported from
//! the user's own tmux config.
//!
//! rlord's server stays rlord's (no prefix, no status bar, only rlord's keys
//! in the `root` table). A session with the profile on gets, on top of that,
//! session-scoped:
//!
//! - `key-table rlord-user` — a copy of the user's root table (so the list
//!   page, which keeps `root`, never sees their bindings);
//! - their `prefix`, status bar and every other session option;
//! - their window options, also on windows they open later (a per-session
//!   `after-new-window` hook).
//!
//! **Import** asks tmux what the config produced, rather than parsing it:
//! start a scratch server with the user's config (tmux finds it itself) and
//! another with none, dump keys and options, and sort the difference. That
//! sees through `if-shell`, `%if`, `source-file` and plugins alike. Session
//! restoring plugins (resurrect, continuum) would restore the user's real
//! sessions into the scratch server, so the scratch server runs under a
//! mirror of `$HOME` with those plugin directories left out.
//!
//! Files (in the data dir), regenerated by every import:
//! - `tmux.user.conf` — bindings, `@` options, safe server options; sourced
//!   by the server config.
//! - `tmux.user.session.conf` / `tmux.user.window.conf` — option lines
//!   applied per session (`source-file -t`).
//! - `tmux.user.report.txt` — what was imported, what was left out and why.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::{Duration, Instant};

use anyhow::{bail, Context, Result};

use crate::paths;

/// The key table holding the user's root bindings.
pub const TABLE: &str = "rlord-user";

/// Plugins that restore or save whole tmux sessions: they would fight rlord
/// (and, at import, restore the user's real sessions into a scratch server).
const DENIED_PLUGINS: &[&str] = &["tmux-resurrect", "tmux-continuum"];

/// Session options rlord owns (or that would break rlord) — never imported.
const SKIP_SESSION: &[&str] = &[
    "key-table",
    "detach-on-destroy",
    "destroy-unattached",
    "set-titles-string",
    "lock-after-time",
    "lock-command",
];

/// Session options rlord's server config sets away from tmux's defaults: a
/// profile carries the user's value even when it is tmux's default.
const RLORD_CHANGED: &[&str] = &[
    "status",
    "prefix",
    "prefix2",
    "mouse",
    "history-limit",
    "set-titles",
    "default-terminal",
];

/// Window/pane options rlord owns.
const SKIP_WINDOW: &[&str] = &["remain-on-exit", "remain-on-exit-format", "window-size"];

/// Server options that are safe to share with the whole rlord server.
const SAFE_SERVER: &[&str] = &[
    "set-clipboard",
    "copy-command",
    "buffer-limit",
    "extended-keys",
    "focus-events",
    "editor",
    "message-limit",
    "prompt-history-limit",
    "command-alias",
    "terminal-overrides",
    "terminal-features",
];

pub fn keys_path() -> PathBuf {
    paths::data_dir().join("tmux.user.conf")
}
pub fn session_path() -> PathBuf {
    paths::data_dir().join("tmux.user.session.conf")
}
pub fn window_path() -> PathBuf {
    paths::data_dir().join("tmux.user.window.conf")
}
pub fn report_path() -> PathBuf {
    paths::data_dir().join("tmux.user.report.txt")
}

/// Whether a profile has been imported.
pub fn exists() -> bool {
    keys_path().exists() && session_path().exists() && window_path().exists()
}

/// Remove the imported profile.
pub fn remove() -> Result<()> {
    for p in [keys_path(), session_path(), window_path(), report_path()] {
        if p.exists() {
            std::fs::remove_file(&p)?;
        }
    }
    Ok(())
}

/// A profile, ready to write.
#[derive(Debug, Default)]
pub struct Profile {
    pub keys: String,
    pub session: String,
    pub window: String,
    pub report: Report,
}

#[derive(Debug, Default)]
pub struct Report {
    /// Config files tmux loaded (empty: the user has no tmux config).
    pub config_files: Vec<String>,
    /// Bindings imported, per key table (root is reported as `root`).
    pub tables: BTreeMap<String, usize>,
    pub session_opts: usize,
    pub window_opts: usize,
    pub server_opts: Vec<String>,
    /// Notable session options, for the summary (prefix, status, mouse).
    pub highlights: Vec<String>,
    /// (what, why) for everything left out.
    pub dropped: Vec<(String, String)>,
    /// Plugin directories hidden from the scratch server.
    pub hidden_plugins: Vec<String>,
}

impl Report {
    pub fn render(&self) -> String {
        let mut s = String::new();
        if self.config_files.is_empty() {
            s.push_str("no tmux config found: your profile is stock tmux (prefix C-b)\n");
        } else {
            s.push_str(&format!("from: {}\n", self.config_files.join(", ")));
        }
        let tables: Vec<String> = self
            .tables
            .iter()
            .map(|(t, n)| format!("{t} {n}"))
            .collect();
        s.push_str(&format!("bindings: {}\n", tables.join(", ")));
        s.push_str(&format!(
            "options: {} session, {} window (applied only to sessions with the profile on)\n",
            self.session_opts, self.window_opts
        ));
        if !self.highlights.is_empty() {
            s.push_str(&format!("  {}\n", self.highlights.join("  ")));
        }
        if !self.server_opts.is_empty() {
            s.push_str(&format!(
                "server-wide (safe): {}\n",
                self.server_opts.join(", ")
            ));
        }
        if !self.hidden_plugins.is_empty() {
            s.push_str(&format!(
                "plugins left out: {}\n",
                self.hidden_plugins.join(", ")
            ));
        }
        if !self.dropped.is_empty() {
            s.push_str(&format!("left out ({}):\n", self.dropped.len()));
            for (what, why) in &self.dropped {
                s.push_str(&format!("  {what}  — {why}\n"));
            }
        }
        s
    }
}

/// Write the profile files.
pub fn write(p: &Profile) -> Result<()> {
    let dir = paths::data_dir();
    std::fs::create_dir_all(&dir)?;
    std::fs::write(keys_path(), &p.keys)?;
    std::fs::write(session_path(), &p.session)?;
    std::fs::write(window_path(), &p.window)?;
    std::fs::write(report_path(), p.report.render())?;
    Ok(())
}

/// Import the user's tmux config. `reserved` are rlord's own keys (never
/// taken over in the user's table).
pub fn import(reserved: &[&str]) -> Result<Profile> {
    let tag = format!("rlord-import-{}", std::process::id());
    let fake_home = std::env::temp_dir().join(&tag);
    let _ = std::fs::remove_dir_all(&fake_home);
    let home = std::env::var_os("HOME")
        .map(PathBuf::from)
        .context("HOME is not set")?;
    let mut hidden = Vec::new();
    mirror(&home, &fake_home, Path::new(""), HOME_DESCEND, &mut hidden)?;
    // A custom XDG_CONFIG_HOME inside $HOME is covered by the mirror; one
    // elsewhere gets its own.
    let xdg = std::env::var_os("XDG_CONFIG_HOME")
        .map(PathBuf::from)
        .filter(|p| !p.as_os_str().is_empty());
    let xdg_env = match xdg {
        Some(x) if x.starts_with(&home) => Some(fake_home.join(x.strip_prefix(&home)?)),
        Some(x) => {
            let dst = fake_home.join(".rlord-xdg");
            mirror(&x, &dst, Path::new(""), XDG_DESCEND, &mut hidden)?;
            Some(dst)
        }
        None => None,
    };

    let made = (|| -> Result<Profile> {
        let user = Scratch::start(&format!("{tag}-user"), None, &fake_home, xdg_env.as_deref())?;
        let base = Scratch::start(
            &format!("{tag}-base"),
            Some(Path::new("/dev/null")),
            &fake_home,
            xdg_env.as_deref(),
        )?;
        let (u, b) = (user.dump(true)?, base.dump(false)?);
        drop(user); // (kills it: Scratch servers die on drop)
        let mut p = classify(&u, &b, reserved);
        validate(&base, &mut p)?;
        Ok(p)
    })();
    // The mirror holds only symlinks, which remove_dir_all does not follow.
    let _ = std::fs::remove_dir_all(&fake_home);
    let mut p = made?;
    let fake = fake_home.to_string_lossy().into_owned();
    let real = home.to_string_lossy().into_owned();
    // The scratch server saw $HOME as the mirror: `~` in the config (hook
    // commands, plugin paths) expanded to it. Point those back at $HOME.
    for f in p
        .report
        .config_files
        .iter_mut()
        .chain([&mut p.keys, &mut p.session, &mut p.window])
    {
        *f = f.replace(&fake, &real);
    }
    hidden.sort();
    hidden.dedup();
    p.report.hidden_plugins = hidden;
    Ok(p)
}

/// Apply each generated file on a clean scratch server; drop the lines tmux
/// rejects (some options print values they won't take back, e.g.
/// `cursor-colour ''`), so the files always apply cleanly in rlord.
fn validate(s: &Scratch, p: &mut Profile) -> Result<()> {
    let window = s
        .run(&["list-windows", "-t", "=import", "-F", "#{window_id}"])?
        .lines()
        .next()
        .context("scratch session has no window")?
        .to_string();
    let tmp = std::env::temp_dir().join(format!("rlord-validate-{}.conf", std::process::id()));
    let try_source = |text: &str, target: Option<&str>| -> Result<(), String> {
        std::fs::write(&tmp, text).map_err(|e| e.to_string())?;
        let t = tmp.to_string_lossy();
        let mut args = vec!["source-file"];
        if let Some(target) = target {
            args.extend(["-t", target]);
        }
        args.push(&t);
        s.run(&args).map(|_| ()).map_err(|e| {
            let e = e.to_string();
            e.strip_prefix("tmux source-file failed: ")
                .unwrap_or(&e)
                .to_string()
        })
    };
    let session_target = "=import:".to_string();
    let parts: [(&mut String, Option<&str>); 3] = [
        (&mut p.keys, None),
        (&mut p.session, Some(&session_target)),
        (&mut p.window, Some(&window)),
    ];
    for (text, target) in parts {
        if try_source(text, target).is_ok() {
            continue; // the whole file applies: done
        }
        let mut kept = String::new();
        for line in text.lines() {
            match try_source(line, target) {
                Ok(()) => {
                    kept.push_str(line);
                    kept.push('\n');
                }
                Err(e) => p.report.dropped.push((
                    short(line.trim_start_matches("set-option ")),
                    format!("tmux won't take it back: {e}"),
                )),
            }
        }
        *text = kept;
    }
    let _ = std::fs::remove_file(&tmp);
    let count = |t: &str| t.lines().filter(|l| !l.starts_with('#')).count();
    p.report.session_opts = count(&p.session);
    p.report.window_opts = count(&p.window);
    Ok(())
}

/// What a scratch server ended up with.
#[derive(Debug, Default)]
struct Dump {
    config_files: Vec<String>,
    keys: String,
    session: String,
    window: String,
    server: String,
    /// `show-hooks -g`.
    hooks: String,
}

struct Scratch {
    socket: String,
    home: PathBuf,
    xdg: Option<PathBuf>,
}

impl Scratch {
    fn cmd(&self) -> Command {
        let mut c = Command::new("tmux");
        c.env_remove("TMUX")
            .env("HOME", &self.home)
            .args(["-L", &self.socket]);
        if let Some(x) = &self.xdg {
            c.env("XDG_CONFIG_HOME", x);
        }
        let utf8 = ["LC_ALL", "LC_CTYPE", "LANG"]
            .iter()
            .find_map(|k| std::env::var(k).ok().filter(|v| !v.is_empty()))
            .is_some_and(|v| v.to_ascii_uppercase().replace('-', "").contains("UTF8"));
        if !utf8 {
            c.env("LC_CTYPE", "en_US.UTF-8");
        }
        c
    }

    fn run(&self, args: &[&str]) -> Result<String> {
        let out = self.cmd().args(args).output().context("running tmux")?;
        if !out.status.success() {
            bail!(
                "tmux {} failed: {}",
                args.first().unwrap_or(&"?"),
                String::from_utf8_lossy(&out.stderr).trim()
            );
        }
        Ok(String::from_utf8_lossy(&out.stdout).to_string())
    }

    /// `conf` None: tmux loads the user's config the way it always does.
    fn start(socket: &str, conf: Option<&Path>, home: &Path, xdg: Option<&Path>) -> Result<Self> {
        let s = Scratch {
            socket: socket.to_string(),
            home: home.to_path_buf(),
            xdg: xdg.map(Path::to_path_buf),
        };
        let _ = s.run(&["kill-server"]);
        let mut c = s.cmd();
        if let Some(conf) = conf {
            c.arg("-f").arg(conf);
        }
        let out = c
            .args(["new-session", "-d", "-s", "import", "-x", "200", "-y", "50"])
            .arg("sleep 600")
            .output()
            .context("running tmux")?;
        if !out.status.success() {
            bail!(
                "tmux could not start with your config: {}",
                String::from_utf8_lossy(&out.stderr).trim()
            );
        }
        Ok(s)
    }

    fn dump(&self, wait_for_plugins: bool) -> Result<Dump> {
        let snap = || -> Result<Dump> {
            Ok(Dump {
                config_files: self
                    .run(&["display-message", "-p", "#{config_files}"])
                    .unwrap_or_default()
                    .trim()
                    .split(',')
                    .filter(|f| !f.is_empty() && *f != "/dev/null")
                    .map(str::to_string)
                    .collect(),
                keys: self.run(&["list-keys"])?,
                session: self.run(&["show-options", "-g"])?,
                window: self.run(&["show-options", "-gw"])?,
                server: self.run(&["show-options", "-s"])?,
                hooks: self.run(&["show-hooks", "-g"]).unwrap_or_default(),
            })
        };
        let mut d = snap()?;
        if !wait_for_plugins {
            return Ok(d);
        }
        // Plugin managers load in the background: wait until nothing has
        // changed for a little while.
        let start = Instant::now();
        let mut stable = 0;
        while stable < 3 && start.elapsed() < Duration::from_secs(10) {
            std::thread::sleep(Duration::from_millis(300));
            let n = snap()?;
            if n.keys == d.keys && n.session == d.session && n.server == d.server {
                stable += 1;
            } else {
                stable = 0;
            }
            d = n;
        }
        Ok(d)
    }
}

impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = self.run(&["kill-server"]);
    }
}

/// Mirror `src` into `dst` with symlinks, descending only into `descend`
/// (relative paths) so denied plugin directories can be left out.
fn mirror(
    src: &Path,
    dst: &Path,
    rel: &Path,
    descend: &[&str],
    hidden: &mut Vec<String>,
) -> Result<()> {
    std::fs::create_dir_all(dst)?;
    for e in std::fs::read_dir(src)? {
        let e = e?;
        let name = e.file_name();
        let r = rel.join(&name);
        let to = dst.join(&name);
        // (`is_dir` follows symlinks: a symlinked ~/.tmux is descended too.)
        if descend.iter().any(|d| Path::new(d) == r) && e.path().is_dir() {
            mirror(&e.path(), &to, &r, descend, hidden)?;
        } else if r.parent().is_some_and(|p| p.ends_with("plugins"))
            && DENIED_PLUGINS.iter().any(|d| name == *d)
        {
            hidden.push(name.to_string_lossy().into_owned());
        } else {
            std::os::unix::fs::symlink(e.path(), &to)?;
        }
    }
    Ok(())
}

const HOME_DESCEND: &[&str] = &[
    ".tmux",
    ".tmux/plugins",
    ".config",
    ".config/tmux",
    ".config/tmux/plugins",
];
const XDG_DESCEND: &[&str] = &["tmux", "tmux/plugins"];

/// One `list-keys` line, split at the table and the key.
struct Binding<'a> {
    flags: &'a str,
    table: &'a str,
    key: &'a str,
    command: &'a str,
}

/// `bind-key [-r] -T <table> <key> <command...>` as printed by `list-keys`.
fn parse_binding(line: &str) -> Option<Binding<'_>> {
    let rest = line.strip_prefix("bind-key")?;
    let t = rest.find(" -T ")?;
    let flags = rest[..t].trim();
    let after = rest[t + 4..].trim_start();
    let (table, after) = after.split_once(char::is_whitespace)?;
    let after = after.trim_start();
    let (key, command) = after.split_once(char::is_whitespace).unwrap_or((after, ""));
    Some(Binding {
        flags,
        table,
        key,
        command: command.trim(),
    })
}

/// `name value` lines from `show-options` → (name, raw value).
fn options(text: &str) -> Vec<(&str, &str)> {
    text.lines()
        .filter(|l| !l.trim().is_empty())
        .map(|l| l.split_once(' ').unwrap_or((l, "")))
        .collect()
}

/// Option name without an array index (`terminal-overrides[2]`).
fn base_name(name: &str) -> &str {
    name.split('[').next().unwrap_or(name)
}

fn classify(user: &Dump, base: &Dump, reserved: &[&str]) -> Profile {
    let mut r = Report {
        config_files: user.config_files.clone(),
        ..Default::default()
    };
    let mut keys = String::from(
        "# Generated by `rlord tmux import` — your tmux bindings, for sessions\n\
         # with your tmux profile on. Re-run the import to refresh.\n",
    );

    // Bindings: every table is replaced wholesale (the dump includes tmux's
    // defaults), with `root` moved to rlord's per-session table.
    let mut lines = Vec::new();
    let mut tables = Vec::new();
    for line in user.keys.lines() {
        let Some(b) = parse_binding(line) else {
            continue;
        };
        let what = format!("{} {}", b.table, b.key);
        let why = if b.table == "root" && reserved.contains(&b.key) {
            Some("rlord's key")
        } else if b.command.contains("kill-server") {
            Some("would stop every rlord session")
        } else if b.command.contains("rlord nav ") {
            Some("old rlord binding")
        } else if DENIED_PLUGINS.iter().any(|p| b.command.contains(p)) {
            Some("session-restore plugin")
        } else {
            None
        };
        if let Some(why) = why {
            r.dropped
                .push((format!("{what}: {}", short(b.command)), why.into()));
            continue;
        }
        let table = if b.table == "root" { TABLE } else { b.table };
        if !tables.contains(&table.to_string()) {
            tables.push(table.to_string());
        }
        *r.tables.entry(b.table.to_string()).or_default() += 1;
        let flags = if b.flags.is_empty() {
            String::new()
        } else {
            format!("{} ", b.flags)
        };
        lines.push(format!(
            "bind-key {flags}-T {table} {} {}",
            b.key, b.command
        ));
    }
    for t in &tables {
        keys.push_str(&format!("unbind-key -aq -T {t}\n"));
    }
    for l in lines {
        keys.push_str(&l);
        keys.push('\n');
    }

    // `@` options (plugin settings, read globally by plugin scripts).
    for (name, value) in options(&user.session) {
        if name.starts_with('@') {
            if DENIED_PLUGINS
                .iter()
                .any(|p| name.contains(p.trim_start_matches("tmux-")))
            {
                continue;
            }
            keys.push_str(&format!("set-option -g {name} {value}\n"));
        }
    }

    // Server options: only what changed, only from the safe list.
    let base_server: Vec<(&str, &str)> = options(&base.server);
    for (name, value) in options(&user.server) {
        if base_server.contains(&(name, value)) {
            continue;
        }
        let b = base_name(name);
        let what = format!("{name} {value}");
        if !SAFE_SERVER.contains(&b) {
            r.dropped
                .push((what, "server-wide: would change the rlord list too".into()));
        } else if value.contains("smcup@") || value.contains("rmcup@") {
            r.dropped
                .push((what, "turns off the alternate screen server-wide".into()));
        } else {
            if name.contains('[') {
                keys.push_str(&format!("set-option -as {b} {value}\n"));
            } else {
                keys.push_str(&format!("set-option -s {name} {value}\n"));
            }
            if !r.server_opts.contains(&b.to_string()) {
                r.server_opts.push(b.to_string());
            }
        }
    }

    // Light/dark hooks (tmux >= 3.6 runs them when the terminal reports a
    // theme change): carried over server-wide, plus a startup pick of the
    // matching one, so rlord follows the system like the user's tmux does.
    // The pane colors they manage aren't frozen into the window options.
    let theme_hooks: Vec<(&str, &str)> = user
        .hooks
        .lines()
        .filter_map(|l| {
            let (name, cmd) = l.split_once(' ')?;
            let name = base_name(name);
            THEME_HOOKS.contains(&name).then_some((name, cmd.trim()))
        })
        .filter(|(_, cmd)| !cmd.is_empty())
        .collect();
    for (name, cmd) in &theme_hooks {
        keys.push_str(&format!("set-hook -g {name} {}\n", tmux_quote(cmd)));
    }
    let hook_cmd = |n: &str| theme_hooks.iter().find(|(h, _)| *h == n).map(|(_, c)| *c);
    if let (Some(dark), Some(light)) = (
        hook_cmd("client-dark-theme"),
        hook_cmd("client-light-theme"),
    ) {
        keys.push_str(&format!(
            "if-shell {} {} {}\n",
            tmux_quote(crate::themes::dark_shell_check()),
            tmux_quote(dark),
            tmux_quote(light)
        ));
    }

    // Session and window options that differ from tmux's defaults (or from
    // rlord's server config).
    let mut session = String::from("# Generated by `rlord tmux import`: session options.\n");
    let base_session: Vec<(&str, &str)> = options(&base.session);
    let base_window: Vec<(&str, &str)> = options(&base.window);
    for (name, value) in options(&user.session) {
        if name.starts_with('@') || SKIP_SESSION.contains(&base_name(name)) {
            continue;
        }
        // Unchanged from tmux's default, and not something rlord's server
        // config changes either: nothing to apply.
        if base_session.contains(&(name, value)) && !RLORD_CHANGED.contains(&base_name(name)) {
            continue;
        }
        session.push_str(&format!("set-option {name} {value}\n"));
        r.session_opts += 1;
        if matches!(name, "prefix" | "status" | "mouse") {
            r.highlights.push(format!("{name} {value}"));
        }
    }
    let mut window = String::from("# Generated by `rlord tmux import`: window options.\n");
    for (name, value) in options(&user.window) {
        if name.starts_with('@') || SKIP_WINDOW.contains(&base_name(name)) {
            continue;
        }
        if base_window.contains(&(name, value)) {
            continue;
        }
        if !theme_hooks.is_empty() && THEMED_WINDOW.contains(&base_name(name)) {
            r.dropped.push((
                format!("{name} {value}"),
                "set by your light/dark theme hooks instead".into(),
            ));
            continue;
        }
        window.push_str(&format!("set-option -w {name} {value}\n"));
        r.window_opts += 1;
    }
    Profile {
        keys,
        session,
        window,
        report: r,
    }
}

/// Hooks tmux runs when the terminal switches between light and dark.
const THEME_HOOKS: &[&str] = &["client-light-theme", "client-dark-theme"];

/// Window options a light/dark theme typically sets: with theme hooks, they
