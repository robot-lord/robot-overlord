#!/usr/bin/env bash
# Point the Homebrew formula at a stable release: write Formula/rlord.rb in
# the tap repo with the release's URLs and checksums, commit, push.
#
#   scripts/update-tap.sh VERSION SHA256SUMS [TAP_REPO]
#
# Users: brew install ayersb/tap/rlord   (brings tmux along)
set -euo pipefail
ver=${1:?version}
sums=${2:?SHA256SUMS file}
tap=${3:-ayersb/homebrew-tap}
repo=ayersb/robot-overlord

sha() { awk -v a="rlord-v$ver-$1.tar.gz" '$2 == a {print $1}' "$sums"; }
mac=$(sha aarch64-apple-darwin)
lx=$(sha x86_64-unknown-linux-musl)
la=$(sha aarch64-unknown-linux-musl)
[[ -n $mac && -n $lx && -n $la ]] || { echo "update-tap: missing checksums in $sums" >&2; exit 1; }

d=$(mktemp -d)
trap 'rm -rf "$d"' EXIT
gh repo clone "$tap" "$d/tap" -- -q
mkdir -p "$d/tap/Formula"
url="https://github.com/$repo/releases/download/v$ver"
cat > "$d/tap/Formula/rlord.rb" <<EOF
# Generated by robot-overlord's scripts/update-tap.sh on each stable release.
class Rlord < Formula
  desc "Run and organize many AI coding-agent sessions in tmux"
  homepage "https://github.com/$repo"
  version "$ver"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "$url/rlord-v$ver-aarch64-apple-darwin.tar.gz"
      sha256 "$mac"
    end
  end

  on_linux do
    on_intel do
      url "$url/rlord-v$ver-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$lx"
    end
    on_arm do
      url "$url/rlord-v$ver-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$la"
    end
  end

  depends_on "tmux"

  def install
    bin.install "rlord"
  end

  def caveats
    <<~EOS
      Once: rlord claude install-hooks   (lets rlord see Claude Code's state)
      Then: rlord
    EOS
  end

  test do
    assert_match "rlord #{version}", shell_output("#{bin}/rlord --version")
  end
end
EOF
cd "$d/tap"
git add Formula/rlord.rb
if git diff --cached --quiet; then
  echo "update-tap: formula already at $ver"
  exit 0
fi
git commit -qm "rlord $ver"
git push -q
echo "update-tap: $tap now installs rlord $ver"
